def 插入代价(路线, 点):
    """把一个点插进开放路线的最小边际长度（也允许接在末尾）。"""
    V = np.asarray(路线, dtype=float).reshape(-1, 2)
    p = np.asarray(点, dtype=float)
    最小 = float(np.hypot(*(p - V[-1])))
    for i in range(len(V) - 1):
        a, b = V[i], V[i + 1]
        最小 = min(最小, float(np.hypot(*(p - a)) + np.hypot(*(p - b))
                               - np.hypot(*(b - a))))
    return 最小


def 可盲清(st, 参数, c, m, 阈值):
    return (m["Rmin"] <= 阈值 and
            st.盲清计数[c] < 参数.get("盲清上限V2", 参数["盲清上限"]))


def 选补测点带覆盖(st, c, m, 位置, 参数):
    """③ 补测点顺带当判空锚点。

    V1 的 `选补测点` 只对「这一测能不能把区域压小、要绕多少路、收不收得到」打分，
    完全不看这一站能不能顺手排掉判空残余。可这两件事用的是同一次停靠：
    机器狗反正要走到那儿去，站在能多排掉几百格的地方是**免费**的。

    打分沿用 V1 的四项，再减去「新排除格数 x 覆盖折价」。折价的单位是秒/格：
    一个专程锚点大约值 150 s、能排掉两三千格，所以 0.02~0.10 s/格 是合理量级。
    折价取 0 时本函数与 V1 逐字等价。
    """
    折价 = 参数.get("补测覆盖折价", 0.0)
    掩码 = st.残余联合() if 折价 > 0 else None
    残余 = st.栅格.点[掩码] if (掩码 is not None and np.any(掩码)) else None
    半径 = st.规划器.半径有效
    最好 = (np.inf, None, None)
    for q in V1.补测点候选(m, 位置, 参数, st.信念[c]):
        d, R = V1.预演(st.信念[c], q, 参数["delta"])
        p收 = V1.保证收信比例(st.信念[c], m, q) if 参数["用收信把握"] else 1.0
        if p收 <= 0.0:
            continue
        行程 = C.距(位置, q) + C.距(q, m["圆心"])
        罚 = 0.0 if R <= C.R_CLEAR else (
            30.0 if R <= 参数["盲清阈值"] else 60.0 + min(R, 400.0))
        罚 += (1.0 - p收) * 参数["空测罚"]
        分 = 行程 / C.V_MOVE + C.T_MEASURE + 罚
        if 残余 is not None:
            覆盖 = int((np.hypot(残余[:, 0] - q[0], 残余[:, 1] - q[1])
                        <= 半径).sum())
            分 -= 折价 * 覆盖
        if 分 < 最好[0]:
            最好 = (分, q, R)
    if 最好[1] is None:
        return V1.选补测点(st.信念[c], m, 位置, 参数)
    return 最好[1], 最好[2]


def 构造任务(st, 位置, 参数):
    """V1 同名函数的 V2 版。两处改动都在本函数里，其余逐字照搬。"""
    盲阈 = 参数.get("盲清阈值V2", 参数["盲清阈值"])
    远阈 = 参数.get("远区盲清阈值", 盲阈)
    绕路上限 = 参数.get("补测绕路上限", float("inf"))

    # ---- 第一遍：能直接去清的先定下来，它们构成后面算绕路的基准路线 ----
    任务, 待补, 缓 = [], [], []
    for c in st.已探测未清除():
        m = st.指标(c)
        if m is None or m.get("空"):
            st.异常.append(f"频道{c}可行集为空")
            继续 = V1.重置信念(st, c)
            if not 继续:
                continue
            m = st.指标(c)
            if m is None or m.get("空"):
                continue
        if m["Rmin"] <= C.R_CLEAR or 可盲清(st, 参数, c, m, 盲阈):
            任务.append({"类型": "清除", "点": m["圆心"], "频道": c})
        else:
            待补.append((c, m))

    # ---- 第二遍：补测点要顺路才去 ----
    if 待补:
        基准 = [位置]
        if 任务:
            顺, _ = C.开放TSP(位置, [t["点"] for t in 任务])
            基准 += [任务[i]["点"] for i in 顺]
        for c, m in 待补:
            q, _ = 选补测点带覆盖(st, c, m, 位置, 参数)
            if q is None:
                continue
            项 = {"类型": "补测", "点": q, "频道": c}
            if m["直径"] > 参数["补测任务上限"]:
                缓.append(项)
                continue
            if 插入代价(基准, q) <= 绕路上限:
                任务.append(项)
                基准.append(tuple(q))      # 后续频道按「已经打算去」的路线算绕路
            elif 可盲清(st, 参数, c, m, 远阈):
                # 绕路太贵：直接去区域里扫射。空枪 3 s + 一个 20 m 排除盘。
                任务.append({"类型": "清除", "点": m["圆心"], "频道": c})
            else:
                缓.append(项)              # 既绕路又不敢盲清：等锚点扫描顺带解决

    # ---- 第三遍：判空锚点（与 V1 完全一致）----
    if np.any(st.残余联合()):
        预扣 = tuple(t["点"] for t in 任务) if 参数["预扣覆盖"] else ()
        路线 = [位置]
        if 任务:
            顺, _ = C.开放TSP(位置, [t["点"] for t in 任务])
            路线 += [任务[i]["点"] for i in 顺]
        for a in st.锚点(预扣点=预扣, 当前位置=位置, 路线=路线):
            任务.append({"类型": "锚点", "点": a, "频道": None})
    if not 任务:
        任务 = 缓                                  # 别把自己饿死
    return 任务


# ================================================================ ④ 巡回加 Or-opt
def or_opt(起点, 点表, 顺序, 最大段=3, 最大轮=10):
    """把长度 1~3 的子段整体搬到别处（可反向）。2-opt 只会反转，搬不动段。

    移动占总时间的 72%，而 V1 的巡回只做最近邻 + 2-opt。Or-opt 是 2-opt 的标准
    补充邻域，通常还能再抠 2~4% 的路程。任务点只有一二十个，暴力枚举即可。
    """
    顺序 = list(顺序)
    n = len(顺序)
    if n < 3:
        return 顺序
    最好 = C.路线长度(起点, 点表, 顺序)
    for _ in range(最大轮):
        改进 = False
        for L in range(1, min(最大段, n - 1) + 1):
            for i in range(n - L + 1):
                段 = 顺序[i:i + L]
                余 = 顺序[:i] + 顺序[i + L:]
                for j in range(len(余) + 1):
                    for s in (段, 段[::-1]):
                        新 = 余[:j] + list(s) + 余[j:]
                        if 新 == 顺序:
                            continue
                        v = C.路线长度(起点, 点表, 新)
                        if v < 最好 - 1e-9:
                            顺序, 最好, 改进 = 新, v, True
                            break
                    if 改进:
                        break
                if 改进:
                    break
            if 改进:
                break
        if not 改进:
            break
    return 顺序


def 开放TSP增强(起点, 点表):
    """V1 的最近邻 + 2-opt，之后再跑一遍 Or-opt。"""
    if not len(点表):
        return [], 0.0
    顺序 = C.最近邻路线(起点, 点表)
    if C.启用2opt:
        顺序 = C.二opt(起点, 点表, 顺序)
    if len(点表) <= 30:
        顺序 = or_opt(起点, 点表, 顺序)
    return 顺序, C.路线长度(起点, 点表, 顺序)


@contextmanager
def 启用V2(用oropt=False):
    """只替换 构造任务（必要时再替换开放TSP）；主循环、信念层、锚点层沿用 V1。"""
    原任务, 原TSP = V1.构造任务, C.开放TSP
    V1.构造任务 = 构造任务
    if 用oropt:
        C.开放TSP = 开放TSP增强
    try:
        yield
    finally:
        V1.构造任务 = 原任务
        C.开放TSP = 原TSP


