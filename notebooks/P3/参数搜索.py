HERE = Path(__file__).resolve().parent
SEED = 20260911
样本数 = 40
确认样本数 = 40


def 造样本(N, 种子=SEED):
    rng = np.random.default_rng(种子)
    return [G.造案例(rng) for _ in range(N)]


def 评估(样本, 参数=None):
    """返回逐局明细表。每一行一局，列里既有时间也有过程计数。"""
    行 = []
    for 案 in 样本:
        后端 = S.本地后端(案)
        狗 = S.机器狗(后端, 现实时限=1e9)
        t0 = time.time()
        r = ST.推荐策略(狗, 参数)
        下 = ST.理论下界(案)
        行.append({
            "源数": 案.源数,
            "虚拟总时间": r["虚拟总时间"],
            "清除成功": r["清除成功"],
            "清除率": r["清除成功"] / 案.源数,
            "平均定位清除时间": r["虚拟总时间"] / max(r["清除成功"], 1),
            "下界2": 下["下界2总时间"],
            "相对下界2": r["虚拟总时间"] / 下["下界2总时间"],
            "检测次数": r["检测次数"], "清除次数": r["清除次数"],
            "程序耗时": time.time() - t0, "异常数": len(r["异常"]),
            **{f"计_{k}": v for k, v in r["计数"].items()},
            **{f"时_{k}": v for k, v in 后端.计时.items()},
        })
    return pd.DataFrame(行)


def 配对(名, 表, 基准表):
    """与基准逐局配对比较。t 值用配对差的标准误。"""
    d = 表["虚拟总时间"].to_numpy() - 基准表["虚拟总时间"].to_numpy()
    se = d.std(ddof=1) / np.sqrt(len(d)) if len(d) > 1 else np.nan
    return {"设置": 名, "平均总时间": 表["虚拟总时间"].mean(),
            "平均定位清除时间": 表["平均定位清除时间"].mean(),
            "清除率": 表["清除率"].mean(),
            "相对下界2": 表["相对下界2"].mean(),
            "配对差": d.mean(), "配对差标准误": se,
            "t": d.mean() / se if se and se > 0 else 0.0,
            "改善局数": int((d < 0).sum()), "变差局数": int((d > 0).sum()),
            "检测次数": 表["检测次数"].mean(),
            "扫描停靠": 表["计_扫描停靠"].mean(),
            "扫描检测": 表["计_扫描检测"].mean(),
            "补测检测": 表["计_补测检测"].mean(),
            "锚点停靠": 表["计_锚点停靠"].mean(),
            "移动s": 表["时_移动"].mean(), "检测s": 表["时_检测"].mean(),
            "程序耗时": 表["程序耗时"].mean(), "异常": int(表["异常数"].sum())}


def 打印(标题, 行表):
    print(f"\n{标题}")
    print(f"    {'设置':>26} {'总时间':>9} {'平均/源':>9} {'清除率':>7} "
          f"{'配对差':>9} {'±SE':>7} {'t':>7} {'好/坏':>9} "
          f"{'检测':>6} {'扫停':>6} {'锚点':>5} {'移动s':>8}")
    for r in 行表:
        print(f"    {str(r['设置']):>26} {r['平均总时间']:>9.1f} "
              f"{r['平均定位清除时间']:>9.1f} {r['清除率']:>7.4f} "
              f"{r['配对差']:>+9.1f} {r['配对差标准误']:>7.1f} {r['t']:>+7.2f} "
              f"{str(r['改善局数']) + '/' + str(r['变差局数']):>9} "
              f"{r['检测次数']:>6.1f} {r['扫描停靠']:>6.1f} "
              f"{r['锚点停靠']:>5.1f} {r['移动s']:>8.0f}")


单扫表 = [
    ("锚点准则", ("覆盖", "覆盖每米")),
    ("锚点每米尺度", (150.0, 400.0, 900.0)),
    ("扫描增益ζ", (0.15, 0.30, 0.45, 0.60, 0.90, 1.40, 1e9)),
    ("盲清阈值", (20.0, 28.0, 36.0, 45.0, 60.0, 90.0)),
    ("精测增益γ", (0.30, 0.50, 0.70, 0.85, 1.00)),
    ("空测罚", (0.0, 45.0, 90.0, 180.0)),
    ("补测κ", ((0.10,), (0.20,), (0.35,), (0.55,), (0.20, 0.35, 0.55))),
    ("补测λ", ((0.30,), (0.50,), (0.70,), (0.30, 0.50, 0.70))),
    ("锚点间距", (100.0, 150.0, 220.0)),
    ("栅格步长", (15.0, 20.0, 30.0)),
]


def main():
    print("问题三 · 策略参数调优")
    print(f"随机种子 {SEED}；单扫样本 {样本数} 局，确认样本 {确认样本数} 局")
    print("所有设置跑同一批算例（公共随机数），比较用逐局配对差。\n")
    样本 = 造样本(样本数)
    基准表 = 评估(样本)
    基准 = 配对("默认参数", 基准表, 基准表)
    打印("零、默认参数（后面所有配对差都相对它）", [基准])
    print("    默认参数：" + "，".join(
        f"{k}={v}" for k, v in ST.默认参数.items()
        if k in ("锚点准则", "锚点每米尺度", "扫描增益ζ", "精测增益γ",
                 "盲清阈值", "空测罚", "补测κ", "补测λ", "锚点间距",
                 "栅格步长")))
    print(f"    单局总时间的标准差 {基准表['虚拟总时间'].std(ddof=1):.0f} s，"
          f"均值的标准误 "
          f"{基准表['虚拟总时间'].std(ddof=1) / np.sqrt(样本数):.0f} s")
    print("    -> 这就是为什么必须配对：非配对比较连 100 秒的差别都分辨不出。")

    print("\n" + "=" * 140)
    print("一、逐个参数单扫（其余参数固定在默认值，同一批算例）")
    print("=" * 140)
    记录, 显著 = [], []
    for 名, 取值表 in 单扫表:
        行表 = []
        for v in 取值表:
            表 = 评估(样本, {名: v})
            r = 配对(f"{名}={v}", 表, 基准表)
            r["参数"], r["取值"] = 名, str(v)
            行表.append(r)
            记录.append(r)
        打印(f"{名}", 行表)
        合格 = [r for r in 行表 if r["清除率"] >= 0.9999]
        好 = min(合格, key=lambda r: r["平均总时间"]) if 合格 else None
        if 好 is not None:
            强 = abs(好["t"]) >= 2.0
            显著.append((名, 好, 强))
            print(f"    -> 名义最优 {好['设置']}：配对差 {好['配对差']:+.1f} "
                  f"± {好['配对差标准误']:.1f} s，t = {好['t']:+.2f}"
                  f"（{'显著' if 强 else '**不显著，按无差别处理**'}）")
    pd.DataFrame(记录).to_csv(HERE / "参数搜索_单扫.csv", index=False,
                              encoding="utf-8-sig")

    print("\n" + "=" * 140)
    print("二、把单扫里**显著**的改动叠加起来")
    print("=" * 140)
    组合 = {}
    for 名, 好, 强 in 显著:
        if 强 and 好["配对差"] < 0:
            组合[名] = dict(单扫表)[名][
                [str(v) for v in dict(单扫表)[名]].index(好["取值"])]
    if not 组合:
        print("    单扫里没有任何一个参数的改动达到显著水平。")
        print("    **结论：默认参数已落在目标函数的平坦区，不再调参。**")
        print("    这本身是一条值得写进论文的结论——它说明策略的表现由结构决定，")
        print("    而不是由参数凑出来的；换一批算例也不会因为参数没调好而崩掉。")
    else:
        print(f"    叠加：{组合}")
        表 = 评估(样本, 组合)
        r = 配对("叠加显著改动", 表, 基准表)
        打印("", [r])
        if abs(r["t"]) < 2.0:
            print("    叠加之后反而不显著，说明各项改动之间存在抵消，"
                  "不宜同时采用。")
        else:
            print("\n" + "=" * 140)
            print("三、换一批独立样本确认（防止调参调到样本上）")
            print("=" * 140)
            确认 = 造样本(确认样本数, 种子=SEED + 777)
            甲, 乙 = 评估(确认), 评估(确认, 组合)
            打印("", [配对("默认参数", 甲, 甲), 配对("调优参数", 乙, 甲)])

    print("\n" + "=" * 140)
    print("四、目标函数的平坦程度（哪些参数需要认真定，哪些随便取）")
    print("=" * 140)
    单 = pd.DataFrame(记录)
    for 名, _ in 单扫表:
        子 = 单[(单["参数"] == 名) & (单["清除率"] >= 0.9999)]
        if not len(子):
            continue
        m = 子["平均总时间"].min()
        内 = 子[子["平均总时间"] <= m * 1.05]
        极差 = 子["平均总时间"].max() - m
        print(f"    {名:<10} 极差 {极差:6.0f} s（{极差 / m:5.1%}），"
              f"5% 以内的取值：{'、'.join(str(x) for x in 内['取值'])}")
    print("\n    极差小于均值标准误若干倍的参数，本质上是不敏感的；")
    print("    论文里给一个值并说明「在这个范围内换取值不影响结论」即可。")

    print("\n" + "=" * 140)
    print("五、清除率：任何参数取值都不能破 1")
    print("=" * 140)
    坏 = 单[单["清除率"] < 0.9999]
    if len(坏):
        print(f"    {'设置':>26} {'清除率':>9} {'异常':>6}")
        for _, r in 坏.iterrows():
            print(f"    {r['设置']:>26} {r['清除率']:>9.4f} {int(r['异常']):>6}")
        print("    -> 这些取值必须排除，不管它们的时间多好看。")
    else:
        print("    全部取值的清除率均为 1.0000，**完备性不依赖参数**。")
        print("    这是策略结构决定的：退出条件是「每个频道要么已清除、要么判空栅格已空」，")
        print("    与任何参数无关；参数只影响用多长时间到达这个条件。")

    print("\n" + "=" * 140)
    print("六、程序运行时间（正式测试限 20 分钟现实时间）")
    print("=" * 140)
    print(f"    单局平均 {基准表['程序耗时'].mean():.2f} s，"
          f"最大 {基准表['程序耗时'].max():.2f} s，"
          f"占 1200 s 预算的 {基准表['程序耗时'].max() / 1200:.2%}")
    print("    计算不是瓶颈；策略里仍设了动作数上限与现实时间留白两道闸，防死循环。")

    基准表.to_csv(HERE / "参数搜索_逐局.csv", index=False, encoding="utf-8-sig")
    print("\n已写入 参数搜索_单扫.csv、参数搜索_逐局.csv")
    return 组合


if __name__ == "__main__":
    with open(HERE / "参数搜索结果.txt", "w", encoding="utf-8") as f:
        原 = sys.stdout
        sys.stdout = f
        try:
             最优 = main()
        finally:
            sys.stdout = 原
    print(f"已写入 {HERE / '参数搜索结果.txt'}")
    print("显著改动：", 最优)
