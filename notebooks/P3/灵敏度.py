import 生成算例 as G
import 策略 as ST

HERE = Path(__file__).resolve().parent
SEED = 20260911

调优参数 = {}


# ================================================================ 单局（子进程里跑）
def 跑一局(任务):
    """按任务描述造一局、跑一局，返回一行汇总。所有随机性都来自 任务['种子']。"""
    rng = np.random.default_rng(任务["种子"])
    案 = G.造案例(rng, **任务.get("造案", {}))
    if 任务.get("R_eff"):                       # 只改真值里的 R_eff，算法侧仍用 1000
        lo, hi = 任务["R_eff"]
        for s in 案.源表:
            s["R_eff"] = float(rng.uniform(lo, hi))
    狗 = S.机器狗(S.本地后端(案), 现实时限=任务.get("时限", 1e9))
    r = ST.推荐策略(狗, dict(调优参数, **任务.get("参数", {})))
    下 = ST.理论下界(案)
    漏 = 案.频道集() - set(r["状态"].已清除)
    误判 = r["状态"].判空集() & 案.频道集()
    未决 = C.频道数 - len(r["状态"].已清除) - len(r["状态"].判空集())
    return {"节": 任务["节"], "情景": 任务["情景"], "源数": 案.源数,
            "未决数": 未决,
            "触发时限": int(any("现实时间" in a for a in r["异常"])),
            "虚拟总时间": r["虚拟总时间"], "清除成功": r["清除成功"],
            "清除率": r["清除成功"] / 案.源数,
            "平均定位清除时间": r["虚拟总时间"] / max(r["清除成功"], 1),
            "相对下界2": r["虚拟总时间"] / 下["下界2总时间"],
            "检测次数": r["检测次数"], "漏清除数": len(漏),
            "判空误判": len(误判), "异常数": len(r["异常"])}


# ================================================================ 任务表
def 建任务(样本数):
    """返回 (任务表, 分节说明)。分节说明里的情景顺序就是表格的行序。"""
    任务, 节表 = [], []

    def 加(节, 情景, 局数, 种子基, **kw):
        for i in range(局数):
            任务.append(dict(kw, 节=节, 情景=情景, 种子=种子基 + i))

    # -------------------------------------------------------------- 一、误差模型
    for 名, kw in [("均匀·独立（基准）", {}),
                   ("三角分布·独立", {"误差分布": "三角"}),
                   ("最坏 ±δ", {"误差模式": "最坏"}),
                   ("空间相关 ℓ=300 m", {"误差模式": "相关", "相关长度": 300.0}),
                   ("空间相关 ℓ=1000 m", {"误差模式": "相关", "相关长度": 1000.0})]:
        加("一", 名, 样本数, SEED, 造案=kw)
    节表.append(("一", "一、示向度误差模型（题目只给了确界 [-1°,1°]，分布是我们的假设）",
                 "（同一批位置与频道，只换误差模型）",
                 "集员估计只用到 |eps| <= delta 这一条，所以清除率在任何误差模型下都"
                 "必须是 1；时间的波动就是本策略对分布假设的敏感度。"))

    # -------------------------------------------------------------- 二、布局
    for 名 in ("均匀", "贴边", "内圈", "聚集"):
        加("二", 名, 样本数, SEED + 11, 造案={"布局": 名})
    节表.append(("二", "二、干扰源的空间布局（题目只说「在目标区域内」）", "",
                 "「内圈」最快（巡回短且原点就能收到大半），「贴边」最慢（要跑到边界，"
                 "而且能在原点收到的源很少）。判空的代价与布局无关，所以贴边局里它占比更低。"))

    # -------------------------------------------------------------- 三、源数
    for n in range(C.源数下界, C.源数上界 + 1):
        加("三", f"源数 = {n}", max(2, 样本数 // 2), SEED + 21, 造案={"源数": n})
    节表.append(("三", "三、干扰源个数（题目给的是区间 10~16）", "",
                 "总时间随源数上升，但平均定位清除时间**下降**：判空这块固定开销"
                 "（空频道越少反而越小）被更多的源分摊，巡回也不随源数线性增长。"))

    # -------------------------------------------------------------- 四、R_eff 分布
    for 名, 区间 in [("U[1000,1500]（基准）", (1000.0, 1500.0)),
                     ("全部取下界 1000", (1000.0, 1000.001)),
                     ("全部取上界 1500", (1499.999, 1500.0)),
                     ("U[1000,1200] 偏小", (1000.0, 1200.0))]:
        加("四", 名, 样本数, SEED + 31, R_eff=区间)
    节表.append(("四", "四、有效接收半径的分布（题目只说在 1000~1500 之间）",
                 "（只改真值里的 R_eff，算法用的下界仍是 1000）",
                 "R_eff 越大越省时间：远处就能拿到示向度，扫描阶段撞见的源更多。"
                 "全取下界是最不利情形，也正是判空推导所依赖的那一端。"))

    # -------------------------------------------------------------- 五、楔形半角
    for d in (1.000, 1.005, 1.02, 1.10, 1.50):
        加("五", f"delta = {d}°", 样本数, SEED + 41, 参数={"delta": d})
    节表.append(("五", "五、算法侧楔形半角 delta（P1 §5.4：两位小数舍入把偏差上界抬到 1.005°）",
                 "（同一批算例，只改算法用的楔形半角）",
                 "delta = 1.000 会把真值排除在楔形之外（概率约 0.125%/次检测），"
                 "表现为可行集变空、频道被迫重置、时间变长甚至漏清除；"
                 "delta 取大则区域偏大、要多测几次。1.005 是「刚好不排除真值」的取法。"))

    # -------------------------------------------------------------- 六、R_eff 下界失真
    # 假设被破坏后，可行集会反复变空 -> 重置信念 -> 又变空，主循环进入**不发指令的空转**，
    # 每轮白白重算一次指标。实测把动作上限设成 50/100/200，指令数、清除数、虚拟时间、
    # 异常数四项完全一致，只有空烧的 CPU 随上限线性增长（默认上限 1500 时单局烧掉
    # 400 s 以上，个别局十几分钟都跑不完）。这一组因此上两道闸：动作上限 60
    # （确定性，主闸）+ 现实时限 60 s（兜底，只在病态局上触发，触发数记进汇总表）。
    for 名, lo in [("真实下界 1000（题面）", 1000.0), ("真实下界 950", 950.0),
                   ("真实下界 900", 900.0), ("真实下界 800", 800.0)]:
        加("六", 名, max(4, 样本数 // 2), SEED + 51, R_eff=(lo, C.R_RECV_MAX),
          参数={"最多动作": 60}, 时限=60.0)
    节表.append(("六", "六、稳健性压力测试：万一 R_eff 的真实下界不是 1000",
                 "（动作上限 60 + 现实时限 60 s 两道闸；正常局 50 轮内收敛，闸不起作用）",
                 "题面白纸黑字写了 1000（正文与附件 2 §2.1 各一次），所以基准档才是实际情形；"
                 "下面几档是压力测试，说明这条假设一旦失真会怎样失效、失效得有多快。"
                 "对策：若演练测试中出现「判空后仍有频道能收到信号」，把排除半径调小即可，"
                 "代价是判空锚点变多。"))
    return 任务, 节表


# ================================================================ 汇总与打印
def 摘(名, 表):
    return {"情景": 名, "局数": len(表), "清除率": 表["清除率"].mean(),
            "全清局占比": float((表["清除率"] >= 1.0).mean()),
            "平均总时间": 表["虚拟总时间"].mean(),
            "平均定位清除时间": 表["平均定位清除时间"].mean(),
            "相对下界2": 表["相对下界2"].mean(),
            "检测次数": 表["检测次数"].mean(),
            "漏清除": int(表["漏清除数"].sum()),
            "判空误判": int(表["判空误判"].sum()),
            "未决频道": int(表["未决数"].sum()),
            "触发时限局数": int(表["触发时限"].sum()),
            "异常": int(表["异常数"].sum())}


def 打印(标题, 行表, 说明=None):
    if 标题:
        print(f"\n{标题}")
    print(f"    {'情景':<26} {'清除率':>8} {'全清局':>8} {'总时间':>9} "
          f"{'平均/源':>9} {'/下界2':>8} {'检测':>7} {'漏清':>6} {'误判':>6} "
          f"{'未决':>6} {'触闸':>6}")
    for r in 行表:
        print(f"    {r['情景']:<26} {r['清除率']:>8.4f} {r['全清局占比']:>8.3f} "
              f"{r['平均总时间']:>9.1f} {r['平均定位清除时间']:>9.1f} "
              f"{r['相对下界2']:>8.3f} {r['检测次数']:>7.1f} "
              f"{r['漏清除']:>6d} {r['判空误判']:>6d} "
              f"{r['未决频道']:>6d} {r['触发时限局数']:>6d}")
    if 说明:
        print(f"    -> {说明}")


def 计时组(局数):
    """第七组：单局现实耗时。要的是独占 CPU 时的真实值，所以串行。"""
    print("\n" + "=" * 118)
    print("七、程序运行时间（正式测试限 20 分钟现实时间）")
    print("=" * 118)
    用时, 指令 = [], []
    for i in range(局数):
        案 = G.造案例(np.random.default_rng(SEED + 61 + i))
        狗 = S.机器狗(S.本地后端(案), 现实时限=1e9)
        t0 = time.time()
        ST.推荐策略(狗, 调优参数)
        用时.append(time.time() - t0)
        指令.append(len(狗.日志))
        PAR.报(f"    [计时] {i + 1}/{局数}  {用时[-1]:.2f}s")
    用时 = np.array(用时)
    print(f"    {len(用时)} 局：平均 {用时.mean():.2f} s，中位 {np.median(用时):.2f} s，"
          f"最大 {用时.max():.2f} s")
    print(f"    正式测试的现实时间预算是 1200 s，本策略的计算占用不到 "
          f"{用时.max() / 1200 * 100:.1f}%。")
    print("    对接官方模拟器时还要加上 HTTP 往返：每个动作一次请求，")
    print(f"    本策略平均约 {np.mean(指令):.0f} 条指令，")
    print("    即使每次往返 20 ms 也只有几秒，远不构成约束。")
    print("    真正需要防的是**死循环**：策略里有动作数上限与现实时间留白两道闸。")
    return {"局数": len(用时), "平均耗时_s": float(用时.mean()),
            "中位耗时_s": float(np.median(用时)), "最大耗时_s": float(用时.max()),
            "平均指令数": float(np.mean(指令)), "现实预算_s": 1200.0,
            "最大占比": float(用时.max() / 1200)}


def main(argv=()):
    快 = "--快" in argv
    样本数 = 8 if 快 else 30
    任务, 节表 = 建任务(样本数)
    print("问题三 · 灵敏度与稳健性")
    print(f"随机种子 {SEED}，每档 {样本数} 局，共 {len(任务)} 局，"
          f"{PAR.进程数} 进程并行\n")

    # 一组一个进程池，每组跑完立刻落盘：哪一组卡住都不至于把前面几组的结果赔进去。
    汇总, 全明细 = [], []
    for 节名, 标题, 副标题, 说明 in 节表:
        print("\n" + "=" * 118)
        print(标题)
        print("=" * 118)
        子任务 = [t for t in 任务 if t["节"] == 节名]
        子 = pd.DataFrame(PAR.并行映射(跑一局, 子任务, 说明=f"第{节名}组"))
        全明细.append(子)
        pd.concat(全明细).to_csv(HERE / "灵敏度逐局.csv", index=False,
                                 encoding="utf-8-sig")
        行表 = [摘(名, 子[子["情景"] == 名]) for 名 in 子["情景"].unique()]
        汇总 += 行表
        打印(副标题, 行表, 说明)
        pd.DataFrame(汇总).to_csv(HERE / "灵敏度汇总.csv", index=False,
                                  encoding="utf-8-sig")
    pd.DataFrame([计时组(8 if 快 else 20)]).to_csv(
        HERE / "灵敏度_运行时间.csv", index=False, encoding="utf-8-sig")
    print("\n已写入 灵敏度汇总.csv、灵敏度逐局.csv、灵敏度_运行时间.csv")


if __name__ == "__main__":
    with PAR.记录到(HERE / "灵敏度结果.txt"):
        main(sys.argv)
