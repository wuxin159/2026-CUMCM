"""问题三 · 第 7 步：灵敏度与稳健性（只算数，不作图）。

策略里凡是**题目没有规定、由我们假设**的东西，都要在这里换掉重跑一遍。
分两类看：

    影响时间的       误差分布、空间相关性、干扰源布局、源数、R_eff 分布
    影响正确性的     楔形半角 delta、R_eff 下界是否真的是 1000

第二类要紧得多：时间差几个百分点只是名次问题，清除率掉下来就是**结论不成立**。
所以本脚本对每一档都同时报「平均总时间」和「清除率」，并对清除率破 1 的情形
单独说明原因。

输出：灵敏度结果.txt、灵敏度汇总.csv
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

import 公共 as C
import 模拟器 as S
import 生成算例 as G
import 策略 as ST

HERE = Path(__file__).resolve().parent
SEED = 20260911
样本数 = 30

调优参数 = {}


def 跑(样本, 参数=None):
    行 = []
    for 案 in 样本:
        后端 = S.本地后端(案)
        狗 = S.机器狗(后端, 现实时限=1e9)
        r = ST.推荐策略(狗, dict(调优参数, **(参数 or {})))
        下 = ST.理论下界(案)
        漏 = 案.频道集() - set(r["状态"].已清除)
        误判 = r["状态"].判空集() & 案.频道集()
        行.append({"源数": 案.源数, "虚拟总时间": r["虚拟总时间"],
                   "清除成功": r["清除成功"], "清除率": r["清除成功"] / 案.源数,
                   "平均定位清除时间": r["虚拟总时间"] / max(r["清除成功"], 1),
                   "相对下界2": r["虚拟总时间"] / 下["下界2总时间"],
                   "检测次数": r["检测次数"], "漏清除数": len(漏),
                   "判空误判": len(误判), "异常数": len(r["异常"])})
    return pd.DataFrame(行)


def 摘(名, 表):
    return {"情景": 名, "局数": len(表), "清除率": 表["清除率"].mean(),
            "全清局占比": float((表["清除率"] >= 1.0).mean()),
            "平均总时间": 表["虚拟总时间"].mean(),
            "平均定位清除时间": 表["平均定位清除时间"].mean(),
            "相对下界2": 表["相对下界2"].mean(),
            "检测次数": 表["检测次数"].mean(),
            "漏清除": int(表["漏清除数"].sum()),
            "判空误判": int(表["判空误判"].sum()),
            "异常": int(表["异常数"].sum())}


def 打印(标题, 行表, 说明=None):
    print(f"\n{标题}")
    print(f"    {'情景':<26} {'清除率':>8} {'全清局':>8} {'总时间':>9} "
          f"{'平均/源':>9} {'/下界2':>8} {'检测':>7} {'漏清':>6} {'误判':>6}")
    for r in 行表:
        print(f"    {r['情景']:<26} {r['清除率']:>8.4f} {r['全清局占比']:>8.3f} "
              f"{r['平均总时间']:>9.1f} {r['平均定位清除时间']:>9.1f} "
              f"{r['相对下界2']:>8.3f} {r['检测次数']:>7.1f} "
              f"{r['漏清除']:>6d} {r['判空误判']:>6d}")
    if 说明:
        print(f"    -> {说明}")


def main():
    print("问题三 · 灵敏度与稳健性")
    print(f"随机种子 {SEED}，每档 {样本数} 局\n")
    汇总 = []

    # ---------------------------------------------------------- 一、误差模型
    print("=" * 118)
    print("一、示向度误差模型（题目只给了确界 [-1°,1°]，分布是我们的假设）")
    print("=" * 118)
    行表 = []
    for 名, kw in [("均匀·独立（基准）", {}),
                   ("三角分布·独立", {"误差分布": "三角"}),
                   ("最坏 ±δ", {"误差模式": "最坏"}),
                   ("空间相关 ℓ=300 m", {"误差模式": "相关", "相关长度": 300.0}),
                   ("空间相关 ℓ=1000 m", {"误差模式": "相关", "相关长度": 1000.0})]:
        rng = np.random.default_rng(SEED)
        样本 = [G.造案例(rng, **kw) for _ in range(样本数)]
        行表.append(摘(名, 跑(样本)))
    汇总 += 行表
    打印("（同一批位置与频道，只换误差模型）", 行表,
         "集员估计只用到 |eps| <= delta 这一条，所以清除率在任何误差模型下都必须是 1；"
         "时间的波动就是本策略对分布假设的敏感度。")

    # ---------------------------------------------------------- 二、干扰源布局
    print("\n" + "=" * 118)
    print("二、干扰源的空间布局（题目只说「在目标区域内」）")
    print("=" * 118)
    行表 = []
    for 名 in ("均匀", "贴边", "内圈", "聚集"):
        rng = np.random.default_rng(SEED + 11)
        样本 = [G.造案例(rng, 布局=名) for _ in range(样本数)]
        行表.append(摘(名, 跑(样本)))
    汇总 += 行表
    打印("", 行表,
         "「内圈」最快（巡回短且原点就能收到大半），「贴边」最慢（要跑到边界，"
         "而且能在原点收到的源很少）。判空的代价与布局无关，所以贴边局里它占比更低。")

    # ---------------------------------------------------------- 三、源数
    print("\n" + "=" * 118)
    print("三、干扰源个数（题目给的是区间 10~16）")
    print("=" * 118)
    行表 = []
    for n in range(C.源数下界, C.源数上界 + 1):
        rng = np.random.default_rng(SEED + 21)
        样本 = [G.造案例(rng, 源数=n) for _ in range(样本数 // 2)]
        行表.append(摘(f"源数 = {n}", 跑(样本)))
    汇总 += 行表
    打印("", 行表,
         "总时间随源数上升，但平均定位清除时间**下降**：判空这块固定开销"
         "（空频道越少反而越小）被更多的源分摊，巡回也不随源数线性增长。")

    # ---------------------------------------------------------- 四、R_eff 分布
    print("\n" + "=" * 118)
    print("四、有效接收半径的分布（题目只说在 1000~1500 之间）")
    print("=" * 118)
    行表 = []
    原低, 原高 = C.R_RECV_MIN, C.R_RECV_MAX
    for 名, (lo, hi) in [("U[1000,1500]（基准）", (1000.0, 1500.0)),
                         ("全部取下界 1000", (1000.0, 1000.001)),
                         ("全部取上界 1500", (1499.999, 1500.0)),
                         ("U[1000,1200] 偏小", (1000.0, 1200.0))]:
        rng = np.random.default_rng(SEED + 31)
        样本 = []
        for _ in range(样本数):
            案 = G.造案例(rng)
            for s in 案.源表:
                s["R_eff"] = float(rng.uniform(lo, hi))
            样本.append(案)
        行表.append(摘(名, 跑(样本)))
    汇总 += 行表
    打印("（只改真值里的 R_eff，算法用的下界仍是 1000）", 行表,
         "R_eff 越大越省时间：远处就能拿到示向度，扫描阶段撞见的源更多。"
         "全取下界是最不利情形，也正是判空推导所依赖的那一端。")

    # ---------------------------------------------------------- 五、楔形半角
    print("\n" + "=" * 118)
    print("五、算法侧楔形半角 delta（P1 §5.4：两位小数舍入把偏差上界抬到 1.005°）")
    print("=" * 118)
    行表 = []
    rng = np.random.default_rng(SEED + 41)
    样本 = [G.造案例(rng) for _ in range(样本数)]
    for d in (1.000, 1.005, 1.02, 1.10, 1.50):
        行表.append(摘(f"delta = {d}°", 跑(样本, {"delta": d})))
    汇总 += 行表
    打印("（同一批算例，只改算法用的楔形半角）", 行表,
         "delta = 1.000 会把真值排除在楔形之外（概率约 0.125%/次检测），"
         "表现为可行集变空、频道被迫重置、时间变长甚至漏清除；"
         "delta 取大则区域偏大、要多测几次。1.005 是「刚好不排除真值」的取法。")

    # ---------------------------------------------------------- 六、R_eff 下界失真
    print("\n" + "=" * 118)
    print("六、稳健性压力测试：万一 R_eff 的真实下界不是 1000")
    print("=" * 118)
    print("    判空的**全部依据**是「no_signal => 距离 > R_eff >= 1000」。")
    print("    如果模拟器实际会生成 R_eff < 1000 的干扰源，排除盘就画大了，")
    print("    可能把一个真源所在的方格划掉，从而误判为空频道。")
    print("    这里人为把真值的 R_eff 下调，看策略在多大偏差下开始漏源。")
    行表 = []
    for 名, lo in [("真实下界 1000（题面）", 1000.0), ("真实下界 950", 950.0),
                   ("真实下界 900", 900.0), ("真实下界 800", 800.0)]:
        rng = np.random.default_rng(SEED + 51)
        样本 = []
        for _ in range(样本数):
            案 = G.造案例(rng)
            for s in 案.源表:
                s["R_eff"] = float(rng.uniform(lo, C.R_RECV_MAX))
            样本.append(案)
        行表.append(摘(名, 跑(样本)))
    汇总 += 行表
    打印("", 行表,
         "题面白纸黑字写了 1000（正文与附件 2 §2.1 各一次），所以基准档才是实际情形；"
         "下面几档是压力测试，说明这条假设一旦失真会怎样失效、失效得有多快。"
         "对策：若演练测试中出现「判空后仍有频道能收到信号」，把排除半径调小即可，"
         "代价是判空锚点变多。")

    # ---------------------------------------------------------- 七、现实运行时间
    print("\n" + "=" * 118)
    print("七、程序运行时间（正式测试限 20 分钟现实时间）")
    print("=" * 118)
    import time
    rng = np.random.default_rng(SEED + 61)
    样本 = [G.造案例(rng) for _ in range(20)]
    用时 = []
    for 案 in 样本:
        狗 = S.机器狗(S.本地后端(案), 现实时限=1e9)
        t0 = time.time()
        ST.推荐策略(狗, 调优参数)
        用时.append(time.time() - t0)
    用时 = np.array(用时)
    print(f"    {len(用时)} 局：平均 {用时.mean():.2f} s，中位 {np.median(用时):.2f} s，"
          f"最大 {用时.max():.2f} s")
    print(f"    正式测试的现实时间预算是 1200 s，本策略的计算占用不到 "
          f"{用时.max() / 1200 * 100:.1f}%。")
    print("    对接官方模拟器时还要加上 HTTP 往返：每个动作一次请求，")
    print(f"    本策略平均约 {int(np.mean([len(狗.日志)]))} 条指令，")
    print("    即使每次往返 20 ms 也只有几秒，远不构成约束。")
    print("    真正需要防的是**死循环**：策略里有动作数上限与现实时间留白两道闸。")

    pd.DataFrame(汇总).to_csv(HERE / "灵敏度汇总.csv", index=False,
                              encoding="utf-8-sig")
    print("\n已写入 灵敏度汇总.csv")


if __name__ == "__main__":
    with open(HERE / "灵敏度结果.txt", "w", encoding="utf-8") as f:
        原 = sys.stdout
        sys.stdout = f
        try:
            main()
        finally:
            sys.stdout = 原
    print(f"已写入 {HERE / '灵敏度结果.txt'}")
