"""问题三 · 第 7 步：灵敏度与稳健性（只算数，不作图）。

七组情景合计约八百局。串行跑要五十分钟且中途没有任何输出，这里把全部情景的
算例摊平成一张任务表交给进程池（见 并行.py），边完成边报进度；第七组量的是
单局的现实耗时，必须独占 CPU，所以仍然串行跑。

    python 灵敏度.py          # 完整版，约 5 分钟
    python 灵敏度.py --快     # 每档 8 局，约 1 分钟，用于改完代码先看一眼
"""
import sys
