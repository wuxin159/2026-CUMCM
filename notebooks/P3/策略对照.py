"""问题三 · 第 6 步：策略对照、消融与分组统计（只算数，不作图）。

一个策略说自己好，要回答三个问题：

    比什么好？   —— 对照组：两个结构完全不同的基线，外加一个不用示向度的极端方案
    离最好差多远？—— 理论下界：已知全部真值时的最优代价
    好在哪一步？ —— 消融：把策略里的每个设计逐个关掉，看时间涨多少

本脚本把这三件事一次做完，并按源数、按布局分组给出明细。

输出：策略对照结果.txt、策略对照汇总.csv、消融汇总.csv、分组统计.csv、逐算例明细.csv
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

import 公共 as C
import 模拟器 as S
import 生成算例 as G
import 策略 as ST

HERE = Path(__file__).resolve().parent
SEED = 20260911
样本数 = 40

# 参数搜索.py 的结论写在这里；改参数只改这一处
调优参数 = {}


def 造样本(N, 种子=SEED, **kw):
    rng = np.random.default_rng(种子)
    return [G.造案例(rng, **kw) for _ in range(N)]


def 跑一批(样本, 策略函数, 参数=None, 锚点表=None):
    行 = []
    for 案 in 样本:
        后端 = S.本地后端(案)
        狗 = S.机器狗(后端, 现实时限=1e9)
        if 锚点表 is not None:
            r = 策略函数(狗, 参数, 锚点表)
        else:
            r = 策略函数(狗, 参数)
        下 = ST.理论下界(案)
        行.append({
            "源数": 案.源数, "空频道数": C.频道数 - 案.源数,
            "虚拟总时间": r["虚拟总时间"], "清除成功": r["清除成功"],
            "清除率": r["清除成功"] / 案.源数,
            "平均定位清除时间": r["虚拟总时间"] / max(r["清除成功"], 1),
            "严格下界": 下["严格下界"],
            "下界1": 下["下界总时间"], "下界2": 下["下界2总时间"],
            "相对严格下界": r["虚拟总时间"] / 下["严格下界"],
            "相对下界1": r["虚拟总时间"] / 下["下界总时间"],
            "相对下界2": r["虚拟总时间"] / 下["下界2总时间"],
            "检测次数": r["检测次数"], "清除次数": r["清除次数"],
            "判空频道数": r["判空频道数"], "异常数": len(r["异常"]),
            **{f"时_{k}": v for k, v in 后端.计时.items()},
            "路程": 后端.路程,
        })
    return pd.DataFrame(行)


def 摘要(名, 表):
    return {"策略": 名, "样本": len(表),
            "清除率": 表["清除率"].mean(),
            "平均总时间": 表["虚拟总时间"].mean(),
            "平均定位清除时间": 表["平均定位清除时间"].mean(),
            "中位总时间": 表["虚拟总时间"].median(),
            "p90总时间": 表["虚拟总时间"].quantile(0.9),
            "相对严格下界": 表["虚拟总时间"].mean() / 表["严格下界"].mean(),
            "相对下界1": 表["虚拟总时间"].mean() / 表["下界1"].mean(),
            "相对下界2": 表["虚拟总时间"].mean() / 表["下界2"].mean(),
            "检测次数": 表["检测次数"].mean(),
            "清除次数": 表["清除次数"].mean(),
            "路程": 表["路程"].mean(),
            "移动s": 表["时_移动"].mean(), "检测s": 表["时_检测"].mean(),
            "切频s": 表["时_切频"].mean(), "清除s": 表["时_清除"].mean(),
            "异常": 表["异常数"].sum()}


def 打印(标题, 行表):
    print(f"\n{标题}")
    print(f"    {'策略':<30} {'清除率':>7} {'总时间':>9} {'平均/源':>9} "
          f"{'中位':>8} {'p90':>8} {'/严格':>7} {'/参照':>7} "
          f"{'检测':>6} {'清除':>6} {'路程m':>8}")
    for r in 行表:
        print(f"    {r['策略']:<30} {r['清除率']:>7.4f} {r['平均总时间']:>9.1f} "
              f"{r['平均定位清除时间']:>9.1f} {r['中位总时间']:>8.1f} "
              f"{r['p90总时间']:>8.1f} {r['相对严格下界']:>7.3f} "
              f"{r['相对下界2']:>7.3f} {r['检测次数']:>6.1f} "
              f"{r['清除次数']:>6.1f} {r['路程']:>8.0f}")


def main():
    print("问题三 · 策略对照、消融与分组统计")
    print(f"随机种子 {SEED}，主样本 {样本数} 局")
    print(f"推荐策略参数：默认 + {调优参数 or '（无覆盖）'}\n")
    样本 = 造样本(样本数)

    # ---------------------------------------------------------- 一、理论下界
    print("=" * 132)
    print("一、两条参照线：严格下界与全知参照")
    print("=" * 132)
    下 = pd.DataFrame([ST.理论下界(案) for 案 in 样本])
    源数 = np.array([案.源数 for 案 in 样本])
    print(f"    平均源数 {源数.mean():.1f}，平均空频道数 "
          f"{C.频道数 - 源数.mean():.1f}\n")
    print("    ① 严格下界（任何策略都不可能低于它；不假设知道源在哪）")
    print(f"    {'组成':<40} {'秒':>9}")
    print(f"    {'MST 行进（边长按 20 m 清除半径削短）':<40} "
          f"{下['严格行进时间'].mean():>9.1f}")
    print(f"    {'每源一次成功清除 5 s':<40} {下['清除时间'].mean():>9.1f}")
    print(f"    {'空频道 7 次检测 x 5 s（不算切频）':<40} "
          f"{下['严格判空检测'].mean():>9.1f}")
    print(f"    {'严格下界合计':<40} {下['严格下界'].mean():>9.1f}"
          f"   （{下['严格下界平均'].mean():.1f} s/源）")
    print("\n    ② 全知参照（**不是下界**，是已知真值时一条可行巡回的代价）")
    print(f"    {'组成':<34} {'秒':>9} {'占下界2':>9}")
    项 = [("访问全部源位置的开放 TSP 行进", 下["行进时间"].mean()),
          ("判空所需的额外锚点行进", (下["含判空TSP路程"] - 下["TSP路程"]).mean()
           / C.V_MOVE),
          ("每源一次成功清除 5 s", 下["清除时间"].mean()),
          ("空频道 7 次检测 x (5+1) s", 下["判空检测时间"].mean())]
    总2 = 下["下界2总时间"].mean()
    for 名, v in 项:
        print(f"    {名:<34} {v:>9.1f} {v / 总2:>9.1%}")
    print(f"    {'参照一（不含判空行进）':<34} {下['下界总时间'].mean():>9.1f}")
    print(f"    {'参照二（含判空行进）':<34} {总2:>9.1f}")
    print(f"    平均每源 {下['下界2平均'].mean():.1f} s；"
          f"严格下界 / 全知参照 = {下['严格下界'].mean() / 总2:.3f}")
    print(f"    源位置自带覆盖之后仍需补的锚点数：{下['补锚点数'].mean():.2f} 个")
    print("    -> 即便把 13 个源位置全走一遍，判空的覆盖仍差 1~3 个锚点。")
    print("       这说明「顺路判空」能省下大部分但不是全部的锚点行程。")

    # ---------------------------------------------------------- 二、策略对照
    print("\n" + "=" * 132)
    print("二、策略对照")
    print("=" * 132)
    汇总, 明细 = [], {}
    for 名, fn, 参数, 锚 in [
            ("推荐策略（一体化滚动时域）", ST.推荐策略, 调优参数, None),
            ("基线一：先扫后清", ST.基线_先扫后清, 调优参数, "auto"),
            ("基线二：逐源处理", ST.基线_逐源, 调优参数, None)]:
        表 = 跑一批(样本, fn, 参数, None if 锚 is None else None)
        明细[名] = 表
        汇总.append(摘要(名, 表))
    盲 = ST.盲清搜索代价()
    汇总.append({"策略": "基线三：盲清搜索（解析）", "样本": 0, "清除率": 1.0,
                 "严格下界": 下["严格下界"].mean(),
                 "相对严格下界": 盲["总时间"] / 下["严格下界"].mean(),
                 "平均总时间": 盲["总时间"], "平均定位清除时间": 盲["总时间"] / 13,
                 "中位总时间": 盲["总时间"], "p90总时间": 盲["总时间"],
                 "相对下界1": 盲["总时间"] / 下["下界总时间"].mean(),
                 "相对下界2": 盲["总时间"] / 总2,
                 "检测次数": 0.0, "清除次数": float(盲["清除点数"]),
                 "路程": 盲["路程"], "移动s": 盲["行进时间"], "检测s": 0.0,
                 "切频s": 0.0, "清除s": 盲["清除时间"], "异常": 0})
    汇总.append({"策略": "全知参照（已知真值的一条巡回）", "样本": len(样本),
                 "清除率": 1.0, "严格下界": 下["严格下界"].mean(),
                 "相对严格下界": 总2 / 下["严格下界"].mean(),
                 "平均总时间": 总2, "平均定位清除时间": 下["下界2平均"].mean(),
                 "中位总时间": 下["下界2总时间"].median(),
                 "p90总时间": 下["下界2总时间"].quantile(0.9),
                 "相对下界1": 总2 / 下["下界总时间"].mean(), "相对下界2": 1.0,
                 "检测次数": np.nan, "清除次数": 源数.mean(),
                 "路程": 下["含判空TSP路程"].mean(),
                 "移动s": 下["含判空TSP路程"].mean() / C.V_MOVE,
                 "检测s": 下["判空检测时间"].mean(), "切频s": 0.0,
                 "清除s": 下["清除时间"].mean(), "异常": 0})
    汇总.sort(key=lambda r: r["平均总时间"])
    打印("（时间单位：秒；清除率必须为 1.0000）", 汇总)
    pd.DataFrame(汇总).to_csv(HERE / "策略对照汇总.csv", index=False,
                              encoding="utf-8-sig")
    推 = [r for r in 汇总 if r["策略"].startswith("推荐")][0]
    print(f"\n    推荐策略 {推['平均总时间']:.1f} s，"
          f"平均定位清除时间 {推['平均定位清除时间']:.1f} s/源，"
          f"是严格下界的 {推['相对严格下界']:.2f} 倍、"
          f"全知参照的 {推['相对下界2']:.2f} 倍。")
    print(f"    盲清搜索（完全不用示向度）需要 {盲['总时间'] / 3600:.1f} 小时、"
          f"{盲['清除点数']} 个清除点——**示向度信息把任务缩短了两个量级**，")
    print("    这也解释了为什么问题三不是一个覆盖搜索问题。")

    print(f"\n    时间去向（推荐策略，{样本数} 局平均）")
    print(f"    {'项目':<10} {'秒':>9} {'折合米':>10} {'占比':>8}")
    合 = 推["移动s"] + 推["检测s"] + 推["切频s"] + 推["清除s"]
    for 名, v in [("移动", 推["移动s"]), ("检测", 推["检测s"]),
                  ("切频道", 推["切频s"]), ("清除", 推["清除s"])]:
        print(f"    {名:<10} {v:>9.1f} {v * C.V_MOVE:>10.0f} {v / 合:>8.1%}")
    print(f"    {'合计':<10} {合:>9.1f} {合 * C.V_MOVE:>10.0f}")

    # ---------------------------------------------------------- 三、消融
    print("\n" + "=" * 132)
    print("三、消融实验：把每个设计逐个关掉")
    print("=" * 132)
    消融 = [摘要("完整策略", 明细["推荐策略（一体化滚动时域）"])]
    项目 = [
        ("关掉顺路扫描（只在专程锚点扫）", {"扫描增益ζ": 1e9}, None),
        ("关掉就地补测（γ=0）", {"精测增益γ": 0.0}, None),
        ("关掉盲清（区域必须 <=20 m 才开枪）", {"盲清阈值": C.R_CLEAR}, None),
        ("关掉锚点预扣覆盖", {"预扣覆盖": False}, None),
        ("关掉「收信把握」判断", {"用收信把握": False}, None),
        ("楔形半角用 1.000°（不留舍入裕度）", {"delta": 1.000}, None),
    ]
    for 名, 参数, _ in 项目:
        p = dict(调优参数)
        p.update(参数)
        消融.append(摘要(名, 跑一批(样本, ST.推荐策略, p)))
    # 结构性消融：模块级开关
    C.启用序约束 = False
    消融.append(摘要("关掉接收半径序约束", 跑一批(样本, ST.推荐策略, 调优参数)))
    C.启用序约束 = True
    C.启用2opt = False
    消融.append(摘要("巡回退化为纯最近邻（无 2-opt）",
                    跑一批(样本, ST.推荐策略, 调优参数)))
    C.启用2opt = True
    打印("（每行只关掉一个设计，其余保持不变）", 消融)
    pd.DataFrame(消融).to_csv(HERE / "消融汇总.csv", index=False,
                              encoding="utf-8-sig")
    基 = 消融[0]["平均总时间"]
    print(f"\n    {'关掉的设计':<34} {'时间变化':>10} {'相对':>8}")
    for r in 消融[1:]:
        print(f"    {r['策略']:<34} {r['平均总时间'] - 基:>+10.1f} "
              f"{r['平均总时间'] / 基 - 1:>+8.1%}")

    # ---------------------------------------------------------- 四、分组
    print("\n" + "=" * 132)
    print("四、分组统计")
    print("=" * 132)
    表 = 明细["推荐策略（一体化滚动时域）"]
    组 = []
    print(f"    按源数：")
    print(f"    {'源数':>6} {'局数':>6} {'平均总时间':>11} {'平均/源':>9} "
          f"{'检测次数':>9} {'相对下界2':>10}")
    for n in sorted(表["源数"].unique()):
        子 = 表[表["源数"] == n]
        print(f"    {n:>6} {len(子):>6} {子['虚拟总时间'].mean():>11.1f} "
              f"{子['平均定位清除时间'].mean():>9.1f} "
              f"{子['检测次数'].mean():>9.1f} {子['相对下界2'].mean():>10.3f}")
        组.append({"分组": "源数", "取值": n, "局数": len(子),
                   "平均总时间": 子["虚拟总时间"].mean(),
                   "平均定位清除时间": 子["平均定位清除时间"].mean(),
                   "检测次数": 子["检测次数"].mean(),
                   "相对下界2": 子["相对下界2"].mean()})
    print("    -> 源数越多总时间越长，但**平均定位清除时间反而下降**：")
    print("       判空的固定开销被更多的源分摊，而巡回路程并不随源数线性增长。")

    print(f"\n    按干扰源布局（每种 {样本数 // 2} 局，源数分布相同）：")
    print(f"    {'布局':>8} {'局数':>6} {'平均总时间':>11} {'平均/源':>9} "
          f"{'清除率':>8} {'相对下界2':>10}")
    for 布局 in ("均匀", "贴边", "内圈", "聚集"):
        子样本 = 造样本(样本数 // 2, 种子=SEED + 31, 布局=布局)
        子 = 跑一批(子样本, ST.推荐策略, 调优参数)
        print(f"    {布局:>8} {len(子):>6} {子['虚拟总时间'].mean():>11.1f} "
              f"{子['平均定位清除时间'].mean():>9.1f} {子['清除率'].mean():>8.4f} "
              f"{子['相对下界2'].mean():>10.3f}")
        组.append({"分组": "布局", "取值": 布局, "局数": len(子),
                   "平均总时间": 子["虚拟总时间"].mean(),
                   "平均定位清除时间": 子["平均定位清除时间"].mean(),
                   "检测次数": 子["检测次数"].mean(),
                   "相对下界2": 子["相对下界2"].mean()})
    pd.DataFrame(组).to_csv(HERE / "分组统计.csv", index=False, encoding="utf-8-sig")

    # ---------------------------------------------------------- 五、具名算例
    print("\n" + "=" * 132)
    print("五、三个具名算例的逐例结果")
    print("=" * 132)
    行 = []
    for 名, 案 in G.具名算例().items():
        后端 = S.本地后端(案)
        狗 = S.机器狗(后端, 现实时限=1e9)
        r = ST.推荐策略(狗, 调优参数, 采集轨迹=True)
        下 = ST.理论下界(案)
        行.append({"算例": 名, "源数": 案.源数,
                   "清除成功": r["清除成功"],
                   "清除率": r["清除成功"] / 案.源数,
                   "虚拟总时间": r["虚拟总时间"],
                   "平均定位清除时间": r["虚拟总时间"] / max(r["清除成功"], 1),
                   "检测次数": r["检测次数"], "清除次数": r["清除次数"],
                   "扫描停靠": r["计数"]["扫描停靠"],
                   "锚点停靠": r["计数"]["锚点停靠"],
                   "路程": 后端.路程, "下界2": 下["下界2总时间"],
                   "相对下界2": r["虚拟总时间"] / 下["下界2总时间"],
                   "异常": ";".join(r["异常"])})
    df = pd.DataFrame(行)
    df.to_csv(HERE / "逐算例明细.csv", index=False, encoding="utf-8-sig")
    pd.set_option("display.width", 220)
    pd.set_option("display.unicode.east_asian_width", True)
    print(df.round(2).to_string(index=False))

    print("\n已写入 策略对照汇总.csv、消融汇总.csv、分组统计.csv、逐算例明细.csv")


if __name__ == "__main__":
    with open(HERE / "策略对照结果.txt", "w", encoding="utf-8") as f:
        原 = sys.stdout
        sys.stdout = f
        try:
            main()
        finally:
            sys.stdout = 原
    print(f"已写入 {HERE / '策略对照结果.txt'}")
