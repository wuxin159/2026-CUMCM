# ================================================================ 锚点规划器
class 锚点规划器:
    """判空锚点的候选点阵与贪心覆盖。

    候选点阵与「候选 x 栅格子格」的关联矩阵在构造时算一次（按栅格步长与候选间距
    缓存，全局共用），之后每次规划只是一次矩阵乘法（几毫秒），
    可以承受滚动时域里的反复调用。

    子格：取栅格中 40 m 的子点阵（步长 20 m 的偶数格），只用于**规划**；
    判空的**判据**始终用完整的 20 m 栅格，两者不混用。
    """

    def __init__(self, 栅格, 间距=150.0, 半径=C.R_RECV_MIN):
        self.栅格 = 栅格
        self.半径有效 = 半径 - 栅格.裕度
        # 候选点阵：六角排布，覆盖到目标圆外 100 m（题面允许在区域外检测）
        点 = []
        行距 = 间距 * np.sqrt(3) / 2
        j = 0
        y = -(C.R_AREA + 100.0)
        while y <= C.R_AREA + 100.0:
            x = -(C.R_AREA + 100.0) + (间距 / 2 if j % 2 else 0.0)
            while x <= C.R_AREA + 100.0:
                if np.hypot(x, y) <= C.R_AREA + 100.0:
                    点.append((x, y))
                x += 间距
            y += 行距
            j += 1
        self.候选 = np.asarray(点, dtype=float)
        # 子采样：20 m 栅格上每隔一格取一个，得到 40 m 子点阵
        步 = 栅格.步长
        idx = np.where((np.round(栅格.点[:, 0] / 步).astype(int) % 2 == 0) &
                       (np.round(栅格.点[:, 1] / 步).astype(int) % 2 == 0))[0]
        self.子索引 = idx
        子点 = 栅格.点[idx]
        d = np.sqrt(((子点[None, :, :] - self.候选[:, None, :]) ** 2).sum(axis=2))
        self.关联 = (d <= self.半径有效).astype(np.float32)

    def 子掩码(self, 掩码):
        return 掩码[self.子索引].astype(np.float32)

    def 残余数(self, 掩码):
        return int(掩码[self.子索引].sum())

    def 新增覆盖(self, 掩码, p):
        d = np.hypot(self.栅格.点[self.子索引, 0] - p[0],
                     self.栅格.点[self.子索引, 1] - p[1])
        return int(np.count_nonzero(掩码[self.子索引] & (d <= self.半径有效)))

    def 插入代价(self, 路线):
        """把每个候选点插进给定开放路线的最小边际长度。路线首元素是当前位置。"""
        V = np.asarray(路线, dtype=float).reshape(-1, 2)
        P = self.候选
        最小 = np.hypot(P[:, 0] - V[-1, 0], P[:, 1] - V[-1, 1])      # 接在末尾
        for i in range(len(V) - 1):
            a, b = V[i], V[i + 1]
            ab = float(np.hypot(*(b - a)))
            d = (np.hypot(P[:, 0] - a[0], P[:, 1] - a[1]) +
                 np.hypot(P[:, 0] - b[0], P[:, 1] - b[1]) - ab)
            最小 = np.minimum(最小, d)
        return 最小

    def 贪心锚点(self, 掩码, 上限=14, 预扣点=(), 当前位置=None, 近邻优先=0.0,
                 准则="覆盖", 每米尺度=400.0, 路线=None):
        """贪心最大覆盖。预扣点是「反正要去的停靠点」，先记它们的覆盖再选锚点。

        近邻优先 > 0 时，在「覆盖数不低于最大值的 (1-近邻优先) 倍」的候选里
        取离当前位置最近的那个——覆盖差不多的两个点，当然挑近的。
        """
        剩 = self.子掩码(掩码)
        子点 = self.栅格.点[self.子索引]
        for p in 预扣点:
            d = np.hypot(子点[:, 0] - p[0], 子点[:, 1] - p[1])
            剩 = 剩 * (d > self.半径有效)
        出 = []
        代价 = (self.插入代价(路线) if (准则 == "覆盖每米" and 路线 is not None)
                else None)
        while 剩.sum() > 0 and len(出) < 上限:
            计数 = self.关联 @ 剩
            if 代价 is not None:
                # 覆盖得多不等于划算：除以「把它插进现有路线要多走多少米」
                得分 = 计数 / (每米尺度 + 代价)
                i = int(np.argmax(得分))
                if 计数[i] <= 0:
                    合格 = np.where(计数 > 0)[0]
                    if not len(合格):
                        break
                    i = int(合格[int(np.argmax(得分[合格]))])
                出.append(tuple(self.候选[i]))
                剩 = 剩 * (1.0 - self.关联[i])
                continue
            i = int(np.argmax(计数))
            if 计数[i] <= 0:
                break                                  # 残余落在所有候选点的射程外
            if 近邻优先 > 0.0 and 当前位置 is not None:
                合格 = np.where(计数 >= (1.0 - 近邻优先) * 计数[i])[0]
                if len(合格):
                    d = np.hypot(self.候选[合格, 0] - 当前位置[0],
                                 self.候选[合格, 1] - 当前位置[1])
                    i = int(合格[int(np.argmin(d))])
            出.append(tuple(self.候选[i]))
            剩 = 剩 * (1.0 - self.关联[i])
        # 去冗余：倒序尝试删除，仍能覆盖就删
        改 = True
        while 改 and len(出) > 1:
            改 = False
            for k in range(len(出) - 1, -1, -1):
                试 = 出[:k] + 出[k + 1:]
                剩 = self.子掩码(掩码)
                for p in list(预扣点) + 试:
                    d = np.hypot(子点[:, 0] - p[0], 子点[:, 1] - p[1])
                    剩 = 剩 * (d > self.半径有效)
                if 剩.sum() == 0:
                    出, 改 = 试, True
                    break
        return 出


_规划器缓存 = {}


def 取规划器(栅格, 间距):
    键 = (栅格.步长, 间距)
    if 键 not in _规划器缓存:
        _规划器缓存[键] = 锚点规划器(栅格, 间距)
    return _规划器缓存[键]


# ================================================================ 信念状态
class 状态:
    """策略侧维护的全部信息。**不含任何真值**。"""

    def __init__(self, 参数):
        self.参数 = 参数
        self.栅格 = C.栅格(参数["栅格步长"])
        self.规划器 = 取规划器(self.栅格, 参数["锚点间距"])
        self.信念 = {c: C.频道信念(c, 参数["delta"]) for c in range(1, C.频道数 + 1)}
        # 每个频道**各有一张**判空栅格掩码。原先只用一张公共掩码，前提是
        # 「未探测频道的无信号历史完全相同」；一旦某个频道因读数矛盾被重置回
        # 未探测状态，这个前提就不成立了，会把它误判成空频道而漏掉一个源。
        # 各自一张的代价只有 20 x 25841 个 bool（约 0.5 MB），换来的是无条件正确。
        self.掩码 = {c: self.栅格.新掩码() for c in range(1, C.频道数 + 1)}
        self.已清除 = set()
        self.已测 = set()                 # (x, y, 频道) 去重：同点同频道重测零信息
        self.已扫点 = set()
        self.盲清计数 = {c: 0 for c in range(1, C.频道数 + 1)}
        self.异常 = []
        self.计数 = {"扫描停靠": 0, "扫描检测": 0, "补测检测": 0,
                     "就地补测": 0, "专程补测": 0, "锚点停靠": 0, "清除停靠": 0}
        self._指标缓存 = {}
        self._锚点缓存 = None
        self._掩码版本 = 0
        self._联合缓存 = None

    # ---------------------------------------------------------- 查询
    @property
    def 未探测(self):
        """还没收到过信号、也没被清除的频道。它们要靠「覆盖判空」才能收尾。"""
        return {c for c in range(1, C.频道数 + 1)
                if c not in self.已清除 and not self.信念[c].收到信号}

    def 判空集(self):
        return {c for c in self.未探测 if not np.any(self.掩码[c])}

    def 残余联合(self):
        """还需要覆盖的方格：各未探测频道残余掩码的并。锚点规划以它为准。"""
        if self._联合缓存 is not None and self._联合缓存[0] == self._掩码版本:
            return self._联合缓存[1]
        待 = [self.掩码[c] for c in self.未探测]
        m = np.zeros(self.栅格.n, dtype=bool) if not 待 else np.logical_or.reduce(待)
        self._联合缓存 = (self._掩码版本, m)
        return m

    def 全部解决(self):
        for c in range(1, C.频道数 + 1):
            if c in self.已清除:
                continue
            if self.信念[c].收到信号:
                return False
            if np.any(self.掩码[c]):
                return False
        return True

    def 指标(self, c):
        b = self.信念[c]
        键 = (c, b.检测次数, len(b.失败清除点), id(b))
        if self._指标缓存.get("键" + str(c)) != 键:
            self._指标缓存["键" + str(c)] = 键
            self._指标缓存[c] = b.指标()
        return self._指标缓存[c]

    def 已探测未清除(self):
        return [c for c in range(1, C.频道数 + 1)
                if c not in self.已清除 and self.信念[c].收到信号]

    def 锚点(self, 预扣点=(), 当前位置=None, 路线=None):
        近 = self.参数.get("锚点近邻优先", 0.0)
        准则 = self.参数.get("锚点准则", "覆盖")
        键 = (self._掩码版本, tuple(sorted(预扣点)), 准则,
              None if (近 <= 0 and 准则 == "覆盖") or 当前位置 is None
              else (round(当前位置[0], -1), round(当前位置[1], -1)))
        if self._锚点缓存 is None or self._锚点缓存[0] != 键:
            self._锚点缓存 = (键, self.规划器.贪心锚点(
                self.残余联合(), 预扣点=预扣点, 当前位置=当前位置,
                近邻优先=近, 准则=准则,
                每米尺度=self.参数.get("锚点每米尺度", 400.0),
                路线=路线))
        return self._锚点缓存[1]

    # ---------------------------------------------------------- 更新
    def _键(self, p, c):
        return (round(float(p[0]), 3), round(float(p[1]), 3), int(c))

    def 记录检测(self, p, c, 回):
        self.已测.add(self._键(p, c))
        r = 回["measure_result"]
        self.信念[c].记录检测(p, r, 回.get("svd_deg"))
        if r == "no_signal":
            # 无信号 => 距离 > R_eff >= 1000，排除以 p 为心、半径 1000 m 的圆盘
            self.掩码[c] = self.栅格.排除圆盘(self.掩码[c], p, C.R_RECV_MIN)
            self._掩码版本 += 1

    def 记录扫描停靠(self, p):
        self.计数["扫描停靠"] += 1
        self.已扫点.add((round(float(p[0]), 1), round(float(p[1]), 1)))

    def 重建掩码(self, c):
        """按该频道**自己的**无信号点重建残余掩码（重置信念时用）。"""
        m = self.栅格.新掩码()
        for p in self.信念[c].无信号点:
            m = self.栅格.排除圆盘(m, p, C.R_RECV_MIN)
        self.掩码[c] = m
        self._掩码版本 += 1

    def 记录清除(self, p, c, 回):
        if 回["clear_result"] == "success":
            self.信念[c].记录清除成功()
            self.已清除.add(c)
        else:
            self.信念[c].记录清除失败(p)
            self.盲清计数[c] += 1


# ================================================================ 几何：预演与补测点
def 预演(信念, q, delta):
    """假设在 q 处收到该频道信号、且示向度恰好指向当前区域形心，问区域会缩成什么样。

    直接把楔形裁到当前多边形上，不另造近似公式——这与真正更新时走的是同一段代码，
    唯一的假设是「示向度指向形心」。返回 (新直径, 新Rmin)；无法预演时返回 (inf, inf)。
    """
    m = 信念.指标()
    if m is None or m.get("空"):
        return np.inf, np.inf
    P = m["多边形"]
    形心 = np.asarray(P, dtype=float).mean(axis=0)
    if C.距(q, 形心) < 1e-6:
        return m["直径"], m["Rmin"]
    θ = C.方位角(q, 形心)
    新 = list(P)
    for a, b, c in C.几何.楔形半平面(q, θ, delta):
        新 = C.几何.裁剪(新, a, b, c)
        if not 新:
            return np.inf, np.inf
    新 = C.几何.去冗余(新)
    if len(新) < 2:
        return 0.0, 0.0
    d, _ = C.P2模型.求直径快(新)
    _, R = C.P2模型.最小覆盖圆快(新)
    return float(d), float(R)


def 保证收信比例(信念, m, q):
    """在 q 处**保证**能收到该频道信号的把握，用可行集里被保证覆盖的比例度量。

    依据（P2 §3.5 的透镜域论证，这里推广到任意观测历史）：
        R_eff 是该源的固有常数，已知 R_eff >= 1000，
        且每一个曾收到信号的点 s 都给出 R_eff >= |s - G|。
    于是对可行集中的一个候选位置 x，只要
        |q - x| <= max(1000, max_s |s - x|)
    就**必定**能在 q 收到它的信号。把这个判据对可行集撒点取比例，
    得到的是收信概率的一个**下界**，不需要假设 R_eff 的分布。

    为什么要它：不做这个判断，策略会在明显收不到的地方硬测一次，
    白花 6 秒换回一个 no_signal。实测里这类空测占了补测的相当一部分。
    """
    P = np.asarray(m["多边形"], dtype=float)
    if len(P) == 0:
        return 0.0
    采样 = [P.mean(axis=0)] + [tuple(p) for p in P]
    if len(P) >= 2:                                  # 边中点，让长条形也有代表点
        采样 += [tuple((P[i] + P[(i + 1) % len(P)]) / 2) for i in range(len(P))]
    信号点 = [np.asarray(s, dtype=float) for s, _ in 信念.信号点]
    好 = 0
    for x in 采样:
        x = np.asarray(x, dtype=float)
        界 = C.R_RECV_MIN
        for s in 信号点:
            界 = max(界, float(np.hypot(*(s - x))))
        if float(np.hypot(q[0] - x[0], q[1] - x[1])) <= 界:
            好 += 1
    return 好 / len(采样)


def 补测点候选(m, 当前位置, 参数, 信念=None):
    """给出若干候选补测点：沿区域长轴取基点、再朝靠近机器狗的一侧作正横侧移。

    正横的道理见 P2 §2.3：新楔形要横切区域的**长轴**才有效，
    沿长轴方向再测一次只是把已知的东西再说一遍。
    侧移量取「区域半长」的一个比例（P2 的 kappa 规则），下限 12 m 以免退化。
    """
    P = np.asarray(m["多边形"], dtype=float)
    D = m["直径"]
    圆心 = np.asarray(m["圆心"], dtype=float)
    _, (A, B) = C.P2模型.求直径快([tuple(p) for p in P])
    A, B = np.asarray(A, dtype=float), np.asarray(B, dtype=float)
    轴 = B - A
    L = float(np.hypot(*轴))
    if L < 1e-9:
        return [tuple(圆心 + np.array([参数["补测最小偏移"], 0.0]))]
    轴 = 轴 / L
    n = np.array([-轴[1], 轴[0]])
    if float(n @ (np.asarray(当前位置, dtype=float) - 圆心)) < 0:
        n = -n
    Λ = D / 2.0
    出 = []
    for λ in 参数["补测λ"]:
        基 = A + λ * (B - A) if D > 120.0 else 圆心
        for κ in 参数["补测κ"]:
            偏 = max(κ * Λ, 参数["补测最小偏移"])
            for s in (1.0, -1.0):
                q = 基 + s * 偏 * n
                出.append((float(q[0]), float(q[1])))
    # 区域很长时，正横侧移点可能离区域另一端太远而收不到信号。
    # 再补几个「贴着区域走」的候选：沿长轴分位点向机器狗一侧小幅侧移。
    for λ in (0.15, 0.35, 0.55, 0.75):
        基 = A + λ * (B - A)
        for 偏 in (max(0.12 * Λ, 参数["补测最小偏移"]), 60.0, 150.0):
            q = 基 + 偏 * n
            出.append((float(q[0]), float(q[1])))
    return 出


def 选补测点(信念, m, 当前位置, 参数):
    """在候选里挑一个：既要一次把区域压进清除半径，又不能为此多绕路，还得收得到。

    评分 = (走到补测点 + 从补测点走到区域中心) / 速度 + 检测耗时
           + 压不下去的罚 + 收不到信号的罚
    第一项就是 P2 §3.2 的「绕路」：补测点不是终点，之后还要走到区域中心去清除。
    最后一项是问题三新加的——单源问题里第二个检测点总在透镜域内，不必操心，
    这里区域可能长达 1500 m，正横点很容易跑到接收范围之外。
    """
    最好 = (np.inf, None, None)
    for q in 补测点候选(m, 当前位置, 参数, 信念):
        d, R = 预演(信念, q, 参数["delta"])
        p收 = 保证收信比例(信念, m, q) if 参数["用收信把握"] else 1.0
        if p收 <= 0.0:
            continue
        行程 = C.距(当前位置, q) + C.距(q, m["圆心"])
        罚 = 0.0 if R <= C.R_CLEAR else (
            30.0 if R <= 参数["盲清阈值"] else 60.0 + min(R, 400.0))
        罚 += (1.0 - p收) * 参数["空测罚"]
        分 = 行程 / C.V_MOVE + C.T_MEASURE + 罚
        if 分 < 最好[0]:
            最好 = (分, q, R)
    if 最好[1] is None:                          # 全都可能收不到：退回贴近区域中心
        方向 = np.asarray(m["圆心"], dtype=float) - np.asarray(当前位置, dtype=float)
        n = float(np.hypot(*方向))
        q = (np.asarray(当前位置, dtype=float) + 方向 * min(1.0, 800.0 / max(n, 1e-9))
             ) if n > 1e-9 else np.asarray(m["圆心"], dtype=float)
        return (float(q[0]), float(q[1])), np.inf
    return 最好[1], 最好[2]


# ================================================================ 推荐策略
def 推荐策略(狗, 参数=None, 采集轨迹=False):
    """一体化滚动时域策略。返回统计字典。"""
    参数 = dict(默认参数, **(参数 or {}))
    st = 状态(参数)
    轨迹 = []
    狗.进入()
    动作 = 0
    while 动作 < 参数["最多动作"]:
        if st.全部解决():
            break
        if 狗.现实剩余 < 参数["现实时间留白"]:
            st.异常.append("现实时间不足，提前收尾")
            break
        位置 = (float(狗.位置[0]), float(狗.位置[1]))

        # ---------- A. 就地整池扫描（未探测频道） ----------
        if 值得扫描(st, 位置, 参数):
            扫描(狗, st, 位置)
            动作 += 1
            if 采集轨迹:
                轨迹.append(("扫描", *位置, 狗.虚拟时刻))
            continue

        # ---------- B. 就地补测（已探测未定位频道） ----------
        做了 = False
        for c in st.已探测未清除():
            m = st.指标(c)
            if m is None or m.get("空"):
                continue
            if m["Rmin"] <= 参数["盲清阈值"]:
                continue
            if st._键(位置, c) in st.已测:
                continue
            p收 = (保证收信比例(st.信念[c], m, 位置)
                   if 参数["用收信把握"] else 1.0)
            if p收 <= 0.0:
                continue
            d, R = 预演(st.信念[c], 位置, 参数["delta"])
            # 期望相对收缩：收不到信号的那部分把握不计入收益。
            # 只按「假设收得到」来判，会在明显收不到的地方白测一次。
            if p收 * (1.0 - d / max(m["直径"], 1e-9)) >= 1.0 - 参数["精测增益γ"]:
                回 = 狗.检测(位置, c)
                st.记录检测(位置, c, 回)
                st.计数["补测检测"] += 1
                st.计数["就地补测"] += 1
                动作 += 1
                做了 = True
                break
        if 做了:
            continue

        # ---------- C. 就地清除 ----------
        目标 = 就地清除目标(st, 位置, 参数)
        if 目标 is not None:
            c, 点 = 目标
            回 = 狗.清除(点, c)
            st.记录清除(点, c, 回)
            动作 += 1
            if 采集轨迹:
                轨迹.append(("清除", *点, 狗.虚拟时刻))
            continue

        # ---------- D. 规划下一站并执行第一段 ----------
        任务 = 构造任务(st, 位置, 参数)
        if not 任务:
            break
        点表 = [t["点"] for t in 任务]
        顺序, _ = C.开放TSP(位置, 点表)
        第一 = 任务[顺序[0]]
        if 第一["类型"] == "清除":
            回 = 狗.清除(第一["点"], 第一["频道"])
            st.记录清除(第一["点"], 第一["频道"], 回)
            if 采集轨迹:
                轨迹.append(("清除", *第一["点"], 狗.虚拟时刻))
        elif 第一["类型"] == "锚点":
            st.计数["锚点停靠"] += 1
            扫描(狗, st, 第一["点"])
            if 采集轨迹:
                轨迹.append(("锚点", *第一["点"], 狗.虚拟时刻))
        else:
            回 = 狗.检测(第一["点"], 第一["频道"])
            st.记录检测(第一["点"], 第一["频道"], 回)
            st.计数["补测检测"] += 1
            st.计数["专程补测"] += 1
            if 采集轨迹:
                轨迹.append(("补测", *第一["点"], 狗.虚拟时刻))
        动作 += 1
    狗.退出()
    return 收尾统计(狗, st, 轨迹 if 采集轨迹 else None)


def 值得扫描(st, p, 参数):
    """在 p 处把未探测池整池测一遍值不值。

    代价是 |池| x 6 s，收益是省下一个专门的锚点行程。把收益折成「覆盖了本该由
    一个锚点覆盖的那一份残余」——即新增覆盖是否达到「残余 / 还需锚点数」的 ζ 倍。
    这个门槛是自归一化的：残余越小、还需锚点越少，单个锚点该覆盖的份额就越大，
    门槛自动抬高，避免临收尾时为了一点点残余反复整池扫描。
    """
    if not st.未探测:
        return False
    if (round(p[0], 1), round(p[1], 1)) in st.已扫点:
        return False
    联合 = st.残余联合()
    残 = st.规划器.残余数(联合)
    if 残 == 0:
        return False
    新增 = st.规划器.新增覆盖(联合, p)
    if 新增 <= 0:
        return False
    还需 = len(st.锚点())
    if 还需 <= 1:
        return True
    return 新增 >= 参数["扫描增益ζ"] * 残 / 还需


def 扫描(狗, st, p):
    """在 p 处把当前未探测池整池测一遍。

    「整池一起测」是刻意的：只有这样，池内各频道的无信号历史才完全相同，
    「公共残余区」这个概念才成立，判空的论证也才干净（每个池内频道的排除盘
    集合都是同一个）。代价是失去了「只测其中几个」的自由度。
    """
    池 = sorted(st.未探测)
    for c in C.排序检测频道(池, 狗.频道):
        if st._键(p, c) in st.已测:
            continue
        回 = 狗.检测(p, c)
        st.记录检测(p, c, 回)
        st.计数["扫描检测"] += 1
    st.记录扫描停靠(p)


def 就地清除目标(st, 位置, 参数):
    """脚下就能打的目标：已定位且清除点离当前位置不超过半米。"""
    for c in st.已探测未清除():
        m = st.指标(c)
        if m is None or m.get("空"):
            continue
        if m["Rmin"] <= C.R_CLEAR and C.距(位置, m["圆心"]) <= 0.5:
            return c, m["圆心"]
    return None


def 构造任务(st, 位置, 参数):
    """把当前所有「必须去的地方」列出来，交给 TSP 排序。

    大区域的补测任务先放进「缓」：区域还有几百米宽时，专程跑一趟补测的收益
    未必抵得上绕路，而判空锚点扫描本来就会把机器狗撒到各处，顺带就把它解决了。
    只有当别的任务都没有时才动用「缓」，免得把自己饿死。

    三类任务：
        清除  已定位（R_min <= 清除半径），或虽略大于清除半径但值得赌一把（盲清）
        补测  已探测但区域还太大，需要换个角度再测一次
        锚点  未探测频道的判空残余，需要专门跑一趟的覆盖点

    锚点在最后算，并且**先扣掉前两类停靠点自带的覆盖**——反正都要去那儿，
    顺手扫一遍就够的话就不必再多跑锚点。这一步是「信息与执行合并」的落点。
    """
    任务, 缓 = [], []
    for c in st.已探测未清除():
        m = st.指标(c)
        if m is None or m.get("空"):
            st.异常.append(f"频道{c}可行集为空")
            继续 = 重置信念(st, c)
            if not 继续:
                continue
            m = st.指标(c)
            if m is None or m.get("空"):
                continue
        if m["Rmin"] <= C.R_CLEAR or (
                m["Rmin"] <= 参数["盲清阈值"] and
                st.盲清计数[c] < 参数["盲清上限"]):
            任务.append({"类型": "清除", "点": m["圆心"], "频道": c})
        else:
            q, _ = 选补测点(st.信念[c], m, 位置, 参数)
            if q is not None:
                项 = {"类型": "补测", "点": q, "频道": c}
                (缓 if m["直径"] > 参数["补测任务上限"] else 任务).append(项)
    if np.any(st.残余联合()):
        预扣 = tuple(t["点"] for t in 任务) if 参数["预扣覆盖"] else ()
        路线 = [位置]
        if 任务:
            顺 , _ = C.开放TSP(位置, [t["点"] for t in 任务])
            路线 += [任务[i]["点"] for i in 顺]
        for a in st.锚点(预扣点=预扣, 当前位置=位置, 路线=路线):
            任务.append({"类型": "锚点", "点": a, "频道": None})
    if not 任务:
        任务 = 缓                                  # 别把自己饿死：没别的可做就去补测
    return 任务


def 重置信念(st, c):
    """可行集变空说明模型与读数矛盾（理论上不该发生，但实测程序必须能兜住）。

    处理：丢掉楔形约束，只保留「排除盘」这类不依赖示向度的硬信息，把频道退回
    未探测池重新走覆盖流程。宁可多花时间，也不能因为一次异常读数就漏掉一个源。
    """
    旧 = st.信念[c]
    新 = C.频道信念(c, st.参数["delta"])
    新.无信号点 = list(旧.无信号点)
    新.失败清除点 = list(旧.失败清除点)
    新.异常 = 旧.异常
    st.信念[c] = 新
    st.重建掩码(c)                       # 退回未探测状态，但用**它自己的**无信号历史
    st._指标缓存.pop(c, None)
    st._指标缓存.pop("键" + str(c), None)
    return False


def 收尾统计(狗, st, 轨迹):
    return {
        "虚拟总时间": 狗.虚拟时刻,
        "检测次数": 狗.检测次数,
        "清除次数": 狗.清除次数,
        "清除成功": 狗.清除成功,
        "判空频道数": len(st.判空集()),
        "计数": dict(st.计数),
        "异常": list(st.异常),
        "状态": st,
        "轨迹": 轨迹,
    }


# ================================================================ 基线一：先扫后清
def 基线_先扫后清(狗, 参数=None, 锚点表=None):
    """先把判空锚点走一遍（每站测遍所有存活频道），再对已定位的源做 TSP 清除。

    这是最容易想到、也最容易讲清楚的方案：信息与执行完全分离。
    它的问题在于**锚点巡回与清除巡回是两条独立的路**，同一片区域要走两遍。
    """
    参数 = dict(默认参数, **(参数 or {}))
    st = 状态(参数)
    狗.进入()
    if 锚点表 is None:
        锚点表 = st.锚点()
        顺序, _ = C.开放TSP((0.0, 0.0), 锚点表)
        锚点表 = [锚点表[i] for i in 顺序]
    # 阶段一：锚点扫描（原点先扫一遍，反正不用走路）
    for p in [(0.0, 0.0)] + list(锚点表):
        池 = sorted(set(range(1, C.频道数 + 1)) - st.已清除)
        for c in C.排序检测频道(池, 狗.频道):
            if st._键(p, c) in st.已测:
                continue
            回 = 狗.检测(p, c)
            st.记录检测(p, c, 回)
        st.记录扫描停靠(p)
    # 阶段二：对已探测频道做 TSP，逐个走到位、必要时补测、再清除
    while True:
        待 = [c for c in st.已探测未清除() if not (st.指标(c) or {}).get("空", True)]
        if not 待:
            break
        点表 = [st.指标(c)["圆心"] for c in 待]
        顺序, _ = C.开放TSP(tuple(狗.位置), 点表)
        c = 待[顺序[0]]
        护 = 0
        while 护 < 8:
            m = st.指标(c)
            if m is None or m.get("空"):
                break
            if m["Rmin"] <= C.R_CLEAR or st.盲清计数[c] >= 参数["盲清上限"]:
                回 = 狗.清除(m["圆心"], c)
                st.记录清除(m["圆心"], c, 回)
                if 回["clear_result"] == "success":
                    break
            else:
                q, _ = 选补测点(st.信念[c], m, tuple(狗.位置), 参数)
                if q is None or st._键(q, c) in st.已测:
                    回 = 狗.清除(m["圆心"], c)
                    st.记录清除(m["圆心"], c, 回)
                    if 回["clear_result"] == "success":
                        break
                else:
                    回 = 狗.检测(q, c)
                    st.记录检测(q, c, 回)
            护 += 1
        if 护 >= 8:
            st.异常.append(f"频道{c}收尾未收敛")
            st.已清除.add(c)                    # 避免死循环，记为放弃
    # 阶段三：残余判空
    护 = 0
    while np.any(st.残余联合()) and 护 < 12:
        锚 = st.锚点()
        if not 锚:
            break
        顺序, _ = C.开放TSP(tuple(狗.位置), 锚)
        扫描(狗, st, 锚[顺序[0]])
        护 += 1
    狗.退出()
    return 收尾统计(狗, st, None)


# ================================================================ 基线二：逐源处理
def 基线_逐源(狗, 参数=None):
    """原点测遍 20 个频道，然后一次只盯一个源，按 P2 的单源办法走完再换下一个。

    这是「把问题二直接套 13 遍」的做法。它没有错，只是把每个源的行程都单独付了一遍。
    """
    参数 = dict(默认参数, **(参数 or {}))
    st = 状态(参数)
    狗.进入()
    扫描(狗, st, (0.0, 0.0))
    护总 = 0
    while 护总 < 60:
        护总 += 1
        待 = [c for c in st.已探测未清除() if not (st.指标(c) or {}).get("空", True)]
        if 待:
            点表 = [st.指标(c)["圆心"] for c in 待]
            顺序, _ = C.开放TSP(tuple(狗.位置), 点表)
            c = 待[顺序[0]]
            护 = 0
            while 护 < 8:
                m = st.指标(c)
                if m is None or m.get("空"):
                    break
                if m["Rmin"] <= C.R_CLEAR or st.盲清计数[c] >= 参数["盲清上限"]:
                    回 = 狗.清除(m["圆心"], c)
                    st.记录清除(m["圆心"], c, 回)
                    if 回["clear_result"] == "success":
                        break
                else:
                    q, _ = 选补测点(st.信念[c], m, tuple(狗.位置), 参数)
                    if q is None or st._键(q, c) in st.已测:
                        回 = 狗.清除(m["圆心"], c)
                        st.记录清除(m["圆心"], c, 回)
                        if 回["clear_result"] == "success":
                            break
                    else:
                        回 = 狗.检测(q, c)
                        st.记录检测(q, c, 回)
                护 += 1
            if 护 >= 8:
                st.异常.append(f"频道{c}收尾未收敛")
                st.已清除.add(c)
            continue
        if np.any(st.残余联合()):
            锚 = st.锚点()
            if not 锚:
                break
            顺序, _ = C.开放TSP(tuple(狗.位置), 锚)
            扫描(狗, st, 锚[顺序[0]])
            continue
        break
    狗.退出()
    return 收尾统计(狗, st, None)


# ================================================================ 基线三：盲清搜索（解析估计）
def 盲清搜索代价(R=C.R_AREA, r=C.R_CLEAR):
    """完全不用示向度，只靠 20 m 清除盘铺满目标圆域的代价（解析估计）。

    六角排布下每个清除盘的有效面积是 (3sqrt3/2) s^2 / 3 = ... 直接用标准结论：
    半径 r 的圆盘六角覆盖平面时，中心点阵的行距为 1.5 r、列距为 sqrt(3) r，
    每点覆盖面积 = (3 sqrt3 / 2) r^2。点数 ≈ 圆域面积 / 该值。
    路程按蛇形走位估计为 点数 x 列距。
    """
    单点面积 = 1.5 * np.sqrt(3.0) * r * r
    点数 = int(np.ceil(np.pi * R * R / 单点面积))
    列距 = np.sqrt(3.0) * r
    路程 = 点数 * 列距
    return {"清除点数": 点数, "路程": 路程,
            "行进时间": 路程 / C.V_MOVE,
            "清除时间": 点数 * C.T_CLEAR_FAIL,
            "总时间": 路程 / C.V_MOVE + 点数 * C.T_CLEAR_FAIL}


# ================================================================ 理论下界
def 理论下界(案例, 空频道判空次数=7, 参数=None):
    """两条参照线。**它们的性质不同，论文里不能混为一谈。**

    ① 严格下界（真正的下界，任何策略都不可能低于它）

           行进 >= MST({原点} ∪ 源位置) / v      （边长按「走到 20 m 内即可」削短）
         + 清除 >= 5 s x 源数                   （每个源至少要成功清除一次）
         + 检测 >= 5 s x 7 x 空频道数           （每个空频道至少 7 次检测，K* = 7）

       三项的依据：任何访问全部目标点的路径都是一棵生成树，故长度不小于 MST；
       清除半径 20 m 意味着只需走到 20 m 内，故每条边可以削掉 2x20 m（与原点相连
       的边削 20 m），削短只会让下界更小，仍然成立；切频道耗时一概不算。
       它**不依赖任何算法**，也不假设知道干扰源在哪。

    ② 全知参照（**不是下界**）：假设一开始就知道全部真值，走一条 2-opt 巡回，
       依次清除，并顺路补上判空所需的锚点。这是一条**可行方案**的代价，
       因此它是「全知最优」的**上界**；而全知最优才是真正的下界。
       所以实测值除以它得到的倍数可能小于 1（内圈布局就出现了 0.995），
       这不矛盾——只说明我们的策略在那类局面上比这条特定的全知路线还短。

    报两条的理由：严格下界太松（MST 比巡回短得多），全知参照贴近但不严格。
    两条一起给，才能既说清「不可能更好的程度」，又说清「已经贴近什么」。
    """
    参数 = dict(默认参数, **(参数 or {}))
    位置 = 案例.位置表()
    空 = C.频道数 - 案例.源数
    清除 = 案例.源数 * C.T_CLEAR_OK

    # ① 严格下界
    MST = C.最小生成树长度(位置, 收缩=2 * C.R_CLEAR, 起点收缩=C.R_CLEAR)
    严格判空检测 = 空频道判空次数 * 空 * C.T_MEASURE        # 不算切频，保证是下界
    严格下界 = MST / C.V_MOVE + 清除 + 严格判空检测

    # ② 全知参照
    _, L1 = C.开放TSP((0.0, 0.0), 位置)
    st = 状态(参数)
    补锚 = st.规划器.贪心锚点(st.残余联合(), 预扣点=tuple(位置))
    _, L2 = C.开放TSP((0.0, 0.0), list(位置) + list(补锚))
    判空检测 = 空频道判空次数 * 空 * (C.T_MEASURE + C.T_SWITCH)
    参照 = L2 / C.V_MOVE + 清除 + 判空检测
    return {"MST路程": MST, "严格行进时间": MST / C.V_MOVE,
            "严格判空检测": 严格判空检测,
            "严格下界": 严格下界, "严格下界平均": 严格下界 / 案例.源数,
            "TSP路程": L1, "行进时间": L1 / C.V_MOVE,
            "清除时间": 清除, "判空检测时间": 判空检测,
            "下界总时间": 参照 - (L2 - L1) / C.V_MOVE,   # 只含源点巡回的参照
            "下界平均": (参照 - (L2 - L1) / C.V_MOVE) / 案例.源数,
            "补锚点数": len(补锚), "含判空TSP路程": L2,
            "下界2总时间": 参照, "下界2平均": 参照 / 案例.源数}
