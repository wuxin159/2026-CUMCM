"""问题二 · 把定稿数据导出到 results/，供论文的 PGFPlots 读取。

命名沿用 P1 的体例：results/问题二_*.csv。
等值面与边界曲线按论文版面抽稀——原始网格 7120 点、透镜边界 483 点，
直接交给 PGFPlots 会显著拖慢编译，且版面上分辨不出差别。
抽稀只影响作图，全部数值结论仍以 notebooks/P2/ 下的完整数据为准。
"""
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "results"


def 写(名, 表, 说明):
    OUT.mkdir(exist_ok=True)
    表.to_csv(OUT / 名, index=False, encoding="utf-8-sig")
    print(f"  {名:<28} {len(表):>5} 行   {说明}")


def 读(名):
    return pd.read_csv(HERE / 名, encoding="utf-8-sig")


def main():
    print(f"导出到 {OUT}：")

    # ---------------------------------------------------------- 图：可行集
    写("问题二_可行集.csv", 读("图_先验区域.csv"), "Ω1 的顶点（局部标架）")

    # ---------------------------------------------------------- 图：交会几何
    写("问题二_交会示意.csv", 读("图_交会示意.csv"), "两楔形的中线与 ±δ 边界")
    顶 = 读("图_定位区域顶点.csv")
    写("问题二_定位区域.csv", 顶[["x", "y"]], "定位区域顶点")

    # ---------------------------------------------------------- 图：两个准则的等值面
    # PGFPlots 的 surf 需要规则网格且按行优先排列，故按 b、a 排序后再抽稀。
    网 = 读("候选区域网格.csv")
    网 = 网[(网["a"] >= -200) & (网["a"] <= 1500) & (网["b"] <= 1000)]
    a取 = np.sort(网["a"].unique())[::2]
    b取 = np.sort(网["b"].unique())[::2]
    子 = 网[网["a"].isin(a取) & 网["b"].isin(b取)].sort_values(["b", "a"])
    for 列, 名 in [("时间均值", "问题二_等值面时间.csv"), ("D均值", "问题二_等值面直径.csv")]:
        出 = 子[["a", "b", 列]].rename(columns={列: "z"})
        写(名, 出, f"{len(a取)}×{len(b取)} 网格，surf 用 mesh/rows={len(b取)}")

    # ---------------------------------------------------------- 图：接收可靠域边界
    透 = 读("图_透镜边界.csv")
    段 = []
    for 记, 组 in 透.groupby("来源"):
        心 = 5.0 if 记 == "近端圆" else 1000.0
        角 = np.degrees(np.arctan2(组["y"].to_numpy(), 组["x"].to_numpy() - 心))
        序 = np.argsort(角 if 记 == "近端圆" else 角 % 360.0)
        取 = 组.iloc[序].iloc[::4]                     # 每 4 点取 1，够画光滑弧
        段.append(pd.DataFrame({"x": 取["x"].to_numpy(), "y": 取["y"].to_numpy(),
                                "弧": 记}))
    写("问题二_接收可靠域.csv", pd.concat(段, ignore_index=True), "透镜形边界的两段弧")

    # ---------------------------------------------------------- 图：效率前沿
    写("问题二_效率前沿.csv", 读("效率前沿.csv"), "给定行进距离下的最优 E[D] 与 E[T]")

    # ---------------------------------------------------------- 图：直径随源距
    t = 读("图_直径随距离.csv")
    t = t[t["候选点"].isin(["推荐点(仿真最优)", "纯几何最优", "几乎不侧移"])]
    映 = {"推荐点(仿真最优)": "本文策略", "纯几何最优": "几何准则最优", "几乎不侧移": "近似径向"}
    宽 = t.assign(策略=t["候选点"].map(映)).pivot_table(
        index="rho", columns="策略", values="直径").reset_index()
    宽 = 宽.iloc[::2]
    写("问题二_直径随源距.csv", 宽, "三个候选点的 D(ρ) 曲线")

    # ---------------------------------------------------------- 表：策略对照
    对 = 读("策略对照汇总.csv")
    写("问题二_策略对照.csv", 对, "各策略的平均总清除时间与相对下界")

    # ---------------------------------------------------------- 表：候选区域边界验证
    写("问题二_候选区域验证.csv", 读("候选区域边界验证.csv"), "区域内外各点的实测耗时")

    print("\n注：论文图表一律引用 results/ 下的这些文件；")
    print("    notebooks/P2/ 保留完整数据与全部中间结果，供复现与追溯。")


if __name__ == "__main__":
    main()
