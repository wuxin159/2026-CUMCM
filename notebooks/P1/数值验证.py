def 造两点(phi_deg, r1, r2, e1=0.0, e2=0.0):
    """干扰源置于原点，两检测点距其 r1、r2，交会角 phi，示向度各带误差 e1、e2。"""
    G = np.array([0.0, 0.0])
    S1 = np.array([-r1, 0.0])
    S2 = np.array([-r2 * math.cos(phi_deg * DEG), -r2 * math.sin(phi_deg * DEG)])
    th1 = math.degrees(math.atan2(*(G - S1)[::-1])) + e1
    th2 = math.degrees(math.atan2(*(G - S2)[::-1])) + e2
    return np.array([S1, S2]), np.array([th1, th2])


