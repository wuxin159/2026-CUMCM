def 圆截断(顶点, R, 边数=20000):
    多 = [tuple(p) for p in 顶点]
    for k in range(边数):
        ang = 2 * math.pi * k / 边数
        多 = 算法.裁剪(多, math.cos(ang), math.sin(ang), R)
        if not 多:
            return []
    return 算法.去冗余(多)


