# ================================================================ ① 代价模型（从题面重写）
def 重算虚拟时钟(日志):
    """按附件 1 表 1 与附件 2 §4 从零重算。**不引用 模拟器.py 的任何常数。**

        移动耗时 = 直线距离 / 5
        /measure = 移动 + (频道变了 ? 1 : 0) + 5
        /clear   = 移动 + (清除成功 ? 5 : 3)，不切频道
        /enter、/exit 不推进
    """
    位置 = np.zeros(2)
    频道 = 1
    t = 0.0
    出 = []
    for 条 in 日志:
        if 条["动作"] in ("enter", "exit"):
            出.append(t)
            continue
        p = np.array([条["x"], 条["y"]], dtype=float)
        t += float(np.hypot(*(p - 位置))) / 5.0
        位置 = p
        if 条["动作"] == "measure":
            if int(条["频道"]) != 频道:
                t += 1.0
                频道 = int(条["频道"])
            t += 5.0
        else:
            t += 5.0 if 条["结果"] == "success" else 3.0
        出.append(t)
    return 出


# ================================================================ ② 可行性判据（从题面重写）
def 题面可行(真源, 观测表, delta=C.DELTA_算法):
    """真源位置是否与全部观测相容。**判据完全按题面重写**，不复用 公共.py。

    写成一条**存在性条件**：是否存在 R_eff ∈ [1000,1500] 与定向方向 u（或全向）
    使全部观测自洽。这样一次性把距离、覆盖角、示向度三件事都包含进去，
    比逐条翻译题面更不容易漏。
    """
    G = np.asarray([真源["x"], 真源["y"]], dtype=float)
    朝向 = 真源["定向方向"]
    for 位置, 结果, svd in 观测表:
        p = np.asarray(位置, dtype=float)
        d = float(np.hypot(*(p - G)))
        在角内 = (朝向 is None) or float((p - G) @ C.单位向量(朝向)) >= 0.0
        if 结果 == "no_signal":
            if d <= C.R_RECV_MIN and 在角内:
                return False, "no_signal 但距离与角度都满足，应当收到"
        elif 结果 == "near":
            if d > C.R_NEAR or not 在角内:
                return False, "near 但距离超过 5 m 或不在覆盖角内"
        elif 结果 == "direction":
            if d <= C.R_NEAR or d > C.R_RECV_MAX or not 在角内:
                return False, "direction 但距离或角度不合题面"
            真角 = C.方位角(p, G)
            if abs(float(C.角差(svd, 真角))) > delta + 1e-9:
                return False, f"示向度偏差 {abs(float(C.角差(svd, 真角))):.4f}° 超过 {delta}°"
    return True, ""


def 真源在可行集内(st, 频道, 真源, 栅格):
    """算法维护的可行集是否仍含真源。分「已探测」与「未探测」两种表示。

    已探测：真源必须落在凸多边形内（多边形是超集，落不进去就是漏判了）。
    未探测：真源所在方格的**相应扇区**必须仍未被排除——
            定向源看它自己的定向方向落在哪个扇区；
            全向源要求该方格的**任何**扇区都没被排除
            （排除一个扇区就意味着有个无信号点落在保证接收距离内，
              而全向源在距离内必然收得到，与观测矛盾）。
    """
    b = st.信念[频道]
    G = (真源["x"], 真源["y"])
    if b.收到信号:
        P_ = b.多边形()
        if not P_:
            return False, "可行集为空"
        if not C.几何.点在多边形内(G, P_):
            近 = min(C.距(G, v) for v in P_)
            if 近 > 2.0:
                return False, f"真源在多边形外 {近:.2f} m"
        return True, ""
    i = int(np.argmin(np.hypot(栅格.点[:, 0] - G[0], 栅格.点[:, 1] - G[1])))
    掩 = st.掩码[频道][i]
    if 真源["定向方向"] is None:
        if not 掩.all():
            return False, "全向源所在方格已有扇区被排除"
    else:
        j = int(真源["定向方向"] % 360.0 // 栅格.扇宽)
        if not 掩[j]:
            return False, "定向源所在方格的定向扇区被排除"
    return True, ""


# ================================================================ 跑一局并复核
def 复核一局(案例, 参数=None, 记录=True):
    后端 = S.本地后端(案例)
    狗 = S.机器狗(后端, 记录日志=True)
    观测 = {c: [] for c in range(1, C.频道数 + 1)}
    真 = {int(s["频道"]): s for s in 案例.源表}
    违规 = []
    断言数 = 0

    原 = P.状态.记录检测

    def 挂(self, p, c, 回):
        原(self, p, c, 回)
        观测[c].append(((float(p[0]), float(p[1])), 回["measure_result"],
                        回.get("svd_deg")))
        nonlocal 断言数
        if c in 真 and c not in self.已清除:
            断言数 += 1
            ok, 因 = 真源在可行集内(self, c, 真[c], self.栅格)
            if not ok:
                违规.append({"类型": "命题A", "频道": c, "原因": 因})
            ok2, 因2 = 题面可行(真[c], 观测[c], self.参数["delta"])
            if not ok2:
                违规.append({"类型": "题面自洽", "频道": c, "原因": 因2})

    P.状态.记录检测 = 挂
    try:
        r = P.推荐策略(狗, 参数)
    finally:
        P.状态.记录检测 = 原
    st = r["状态"]
    判空误判 = sorted(st.判空集() & set(真))
    未决 = [c for c in range(1, C.频道数 + 1)
            if c not in st.已清除 and (st.信念[c].收到信号 or st.掩码[c].any())]
    重 = 重算虚拟时钟(狗.日志)
    差 = max(abs(a - b["虚拟时刻"]) for a, b in zip(重, 狗.日志)) if 狗.日志 else 0.0
    return {
        "源数": 案例.源数, "定向数": 案例.定向数,
        "清除成功": r["清除成功"], "虚拟总时间": r["虚拟总时间"],
        "断言数": 断言数, "命题A违规": sum(1 for v in 违规 if v["类型"] == "命题A"),
        "题面违规": sum(1 for v in 违规 if v["类型"] == "题面自洽"),
        "判空误判": len(判空误判), "未决频道": len(未决),
        "已清除+判空": len(st.已清除) + len(st.判空集()),
        "计时最大差": 差, "异常数": len(r["异常"]),
    }


