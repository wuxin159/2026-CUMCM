"""问题四 · 灵敏度与稳健性的**数值补充**（默认不在 重跑全部.py 的流程里）。

**本文的灵敏度分析以「证明 + 解析分解」为主**，见 分析记录.md §9：

    §9.1  清除率对全部分布假设的不变性——**可证**，不需要抽样
           （它是命题 A、B 的直接推论，而那两条只用到题给的三条物理界）
    §9.2  时间对定向比例 q 的依赖——把总时间拆成「判空 / 执行 / 定位」三块，
           逐块判断它依不依赖 q，并由引理 D3 给出增长因子的上界 2
    §9.3  时间对其余假设的依赖——同样按三块分解
    §9.4  对题给物理界的压力测试——给结论划边界

**为什么不扫**：最要紧的量（清除率）已被证明是常数，扫描它不产生信息；
时间的依赖关系可以解析分解，分解式给出的是**机理**，扫描只给出**数值**。
抽样的边际信息量是 O(1/sqrt(N))，机时代价是 O(N)。

本脚本保留下来，供需要数值佐证时按档扫描（每档 10 局，约 2 分钟）：
定向比例 q、误差模型、R_eff 分布、布局，以及 R_eff 下界跌破 1000 m 的压力测试。
"""
import sys
from multiprocessing import Pool, cpu_count
from pathlib import Path

import numpy as np
import pandas as pd

import 公共 as C
import 模拟器 as S
import 生成算例 as GEN
import 策略 as P

HERE = Path(__file__).resolve().parent
SEED = 20260912
N档 = 10
_进程数 = max(1, min(cpu_count() - 1, 10))


def _跑(t):
    案, 参数 = t
    狗 = S.机器狗(S.本地后端(案), 记录日志=False)
    r = P.推荐策略(狗, 参数)
    st = r.pop("状态")
    真源 = {int(s["频道"]) for s in 案.源表}
    return {
        "虚拟总时间": r["虚拟总时间"], "清除率": r["清除成功"] / 案.源数,
        "漏清": 案.源数 - r["清除成功"], "检测次数": r["检测次数"],
        "路程": 狗.后端.路程, "未决频道数": r["未决频道数"],
        "判空误判": len(st.判空集() & 真源), "源数": 案.源数, "定向数": 案.定向数,
    }


def 跑档(池, 名, 类别, 造例参数, 策略参数=None):
    例 = GEN.造一批(np.random.default_rng(SEED + 500), N档, **造例参数)
    行 = 池.map(_跑, [(a, 策略参数) for a in 例])
    d = pd.DataFrame(行)
    return {"类别": 类别, "档": 名, "局数": len(d),
            "平均总时间": d["虚拟总时间"].mean(),
            "清除率": d["清除率"].mean(),
            "漏清源数": int(d["漏清"].sum()),
            "判空误判": int(d["判空误判"].sum()),
            "未决局数": int((d["未决频道数"] > 0).sum()),
            "检测次数": d["检测次数"].mean(),
            "路程": d["路程"].mean(),
            "平均定向数": d["定向数"].mean()}


def main():
    pd.set_option("display.width", 230)
    pd.set_option("display.unicode.east_asian_width", True)
    print("问题四 · 灵敏度与稳健性")
    print("=" * 78)
    行 = []
    with Pool(_进程数) as 池:
        # ---------------- 一、对本文假设的灵敏度 ----------------
        print("\n一、对「本文自己写下的假设」的灵敏度\n")
        print("  1) 定向源比例 q —— 问题四新增的、也是最要紧的一个假设")
        for q in (0.0, 0.25, 0.5, 0.75, 1.0):
            r = 跑档(池, f"q={q:.2f}", "定向比例",
                     {"定向比例": q, "两类齐全": 0.0 < q < 1.0})
            行.append(r)
            print(f"     q={q:.2f}  平均定向 {r['平均定向数']:.1f} 个   "
                  f"时间 {r['平均总时间']:8.1f} s   清除率 {r['清除率']:.4f}   "
                  f"检测 {r['检测次数']:.0f}", flush=True)

        print("\n  2) 示向度误差模型（题面只给了支撑区间 [-1°,1°]）")
        for 名, kw in (("均匀独立（基准）", {}),
                       ("三角分布", {"误差分布": "三角"}),
                       ("最坏 ±1°", {"误差模式": "最坏"}),
                       ("空间相关（相关长度 300 m）", {"误差模式": "相关"})):
            r = 跑档(池, 名, "误差模型", kw)
            行.append(r)
            print(f"     {名:<22} 时间 {r['平均总时间']:8.1f} s   "
                  f"清除率 {r['清除率']:.4f}   漏清 {r['漏清源数']}", flush=True)

        print("\n  3) 有效接收半径的分布（题面只给了区间 [1000,1500]）")
        for 名, kw in (("U[1000,1500]（基准）", {}),
                       ("全取下界 1000", {"R_eff范围": (1000.0, 1000.001)}),
                       ("全取上界 1500", {"R_eff范围": (1499.999, 1500.0)}),
                       ("偏小 U[1000,1150]", {"R_eff范围": (1000.0, 1150.0)})):
            r = 跑档(池, 名, "接收半径", kw)
            行.append(r)
            print(f"     {名:<22} 时间 {r['平均总时间']:8.1f} s   "
                  f"清除率 {r['清除率']:.4f}   检测 {r['检测次数']:.0f}", flush=True)

        print("\n  4) 干扰源布局（题面只规定「在区域内」）")
        for 布局 in ("均匀", "贴边", "内圈", "聚集"):
            r = 跑档(池, 布局, "布局", {"布局": 布局})
            行.append(r)
            print(f"     {布局:<22} 时间 {r['平均总时间']:8.1f} s   "
                  f"清除率 {r['清除率']:.4f}   路程 {r['路程']:.0f} m", flush=True)

        # ---------------- 二、对题给物理界的压力测试 ----------------
        print("\n二、对「题给物理界」的压力测试（**不是灵敏度，是给结论划边界**）\n")
        print("  5) 真值的 R_eff 下界跌破题面的 1000 m")
        for 下界 in (1000.0, 950.0, 900.0, 800.0):
            r = 跑档(池, f"R_eff >= {下界:.0f}", "压力·接收半径",
                     {"R_eff范围": (下界, 1500.0)})
            行.append(r)
            print(f"     下界 {下界:6.0f} m   时间 {r['平均总时间']:8.1f} s   "
                  f"清除率 {r['清除率']:.4f}   漏清 {r['漏清源数']}   "
                  f"判空误判 {r['判空误判']}", flush=True)

        print("\n  6) 算法侧的楔形半角取得比题面还紧（δ 不留舍入裕度）")
        for δ in (C.DELTA_算法, 1.0, 0.95):
            r = 跑档(池, f"δ={δ:.3f}°", "压力·楔形半角", {}, {"delta": δ})
            行.append(r)
            print(f"     δ={δ:.3f}°   时间 {r['平均总时间']:8.1f} s   "
                  f"清除率 {r['清除率']:.4f}   漏清 {r['漏清源数']}", flush=True)

    df = pd.DataFrame(行)
    df.to_csv(HERE / "灵敏度汇总.csv", index=False, encoding="utf-8-sig")
    print("\n" + "-" * 78)
    print(df.round(3).to_string(index=False))

    基 = df[(df["类别"] == "定向比例") & (df["档"] == "q=0.50")]["平均总时间"].iloc[0]
    一类 = df[df["类别"].isin(["定向比例", "误差模型", "接收半径", "布局"])]
    print(f"""
------------------------------------------------------------------------------
读法

**第一类（对本文假设）**：{len(一类)} 个档的清除率
{'全部为 1.0000' if (一类['清除率'] >= 1.0).all() else
 f"最低 {一类['清除率'].min():.4f}"}，
平均总时间在 {一类['平均总时间'].min():.0f} ~ {一类['平均总时间'].max():.0f} s 之间
（基准 {基:.0f} s，相对极差 {(一类['平均总时间'].max()-一类['平均总时间'].min())/基:.1%}）。
时间随假设变化是正常的——贴边布局要多走路、定向比例高要多绕到正面；
**要紧的是清除率不随假设变化**，因为它由退出条件保证，与假设无关。

**定向比例 q 这一栏值得单独看**：q 从 0 走到 1，时间单调上升。
q=0 就是问题三的情形（全是全向源），但**判空仍按围堵判据做**——
所以它比问题三的 3300 s 贵得多。这正说明代价来自「**不知道**有没有定向源」，
而不是来自「有定向源」：哪怕一个定向源都没有，只要不能排除它存在的可能，
围堵的账就得照付。

**第二类（对题给界）**：R_eff 的真实下界一旦跌破 1000 m，判空的依据立刻失效，
清除率随之下滑——这不是策略的缺陷，是**题设的作用范围**。
论文里的保证必须写完整：

    在「示向度误差 <= 1°、有效接收半径 >= 1000 m、定向覆盖角 = 180°」
    这三条题给条件下，本策略保证清除全部干扰源。
""")


if __name__ == "__main__":
    with open(HERE / "灵敏度结果.txt", "w", encoding="utf-8") as f:
        原 = sys.stdout
        sys.stdout = f
        try:
            main()
        finally:
            sys.stdout = 原
    print(f"已写入 {HERE / '灵敏度结果.txt'}")
