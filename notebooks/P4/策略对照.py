# ================================================================ 跑一局
def 跑(案例, 策略函数, 参数=None, 采集轨迹=False):
    后端 = S.本地后端(案例)
    狗 = S.机器狗(后端, 记录日志=False)
    t0 = time.time()
    r = 策略函数(狗, 参数, 采集轨迹=采集轨迹) if 采集轨迹 else 策略函数(狗, 参数)
    st = r.pop("状态")
    真源 = {int(s["频道"]) for s in 案例.源表}
    漏判 = sorted(st.判空集() & 真源)        # 判为空、实际有源 —— 绝不允许出现
    出 = {
        "虚拟总时间": r["虚拟总时间"],
        "清除成功": r["清除成功"],
        "源数": 案例.源数,
        "定向数": 案例.定向数,
        "清除率": r["清除成功"] / 案例.源数,
        "平均定位清除时间": r["虚拟总时间"] / max(r["清除成功"], 1),
        "检测次数": r["检测次数"],
        "清除次数": r["清除次数"],
        "路程": 后端.路程,
        "判空频道数": r["判空频道数"],
        "未决频道数": r["未决频道数"],
        "判空误判数": len(漏判),
        "异常数": len(r["异常"]),
        "算时": time.time() - t0,
        **{f"t_{k}": v for k, v in 后端.计时.items()},
        **{f"n_{k}": v for k, v in r["计数"].items()},
    }
    if 采集轨迹:
        出["轨迹"] = r["轨迹"]
    return 出


def _工(任务):
    """子进程的入口。**全局开关必须显式传进来**——它们是模块级变量，不随进程继承。

    消融实验里有三项（2-opt、分类器、全向先验的后验更新）是用模块级开关控制的。
    若只在主进程里改，子进程跑的仍是默认配置，消融差会全部变成 0——
    这类「并行化把实验悄悄改错」的坑比慢一点危险得多，所以宁可写笨一些。
    """
    i, 案, 名, 参数, 开关 = 任务
    C.启用2opt = 开关.get("2opt", True)
    C.启用分类器 = 开关.get("分类器", True)
    P._关闭后验 = 开关.get("关闭后验", False)
    f = getattr(P, 名)
    return {"局": i, **跑(案, f, 参数)}


def 批(案例表, 策略函数, 参数=None, 标签="", 并行=True):
    名 = 策略函数.__name__
    开关 = {"2opt": C.启用2opt, "分类器": C.启用分类器, "关闭后验": P._关闭后验}
    任务 = [(i, 案, 名, 参数, 开关) for i, 案 in enumerate(案例表)]
    if 并行 and _进程数 > 1:
        with _池() as 池:
            行 = list(池.map(_工, 任务))
    else:
        行 = [_工(t) for t in 任务]
    df = pd.DataFrame(sorted(行, key=lambda r: r["局"]))
    df["策略"] = 标签
    return df


def 汇(df, 名):
    return {
        "策略": 名,
        "局数": len(df),
        "清除率": df["清除率"].mean(),
        "全清局数": int((df["清除率"] >= 1.0).sum()),
        "判空误判局数": int((df["判空误判数"] > 0).sum()),
        "漏清源数": int((df["源数"] - df["清除成功"]).sum()),
        "未决局数": int((df["未决频道数"] > 0).sum()),
        "平均总时间": df["虚拟总时间"].mean(),
        "中位总时间": df["虚拟总时间"].median(),
        "p90总时间": df["虚拟总时间"].quantile(0.9),
        "平均定位清除时间": df["虚拟总时间"].sum() / max(df["清除成功"].sum(), 1),
        "平均检测次数": df["检测次数"].mean(),
        "平均路程": df["路程"].mean(),
        "平均算时": df["算时"].mean(),
    }


