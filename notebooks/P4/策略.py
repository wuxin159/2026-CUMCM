# ================================================================ 锚点规划器
class 锚点规划器:
    """判空锚点的候选点阵与贪心覆盖（问题四版：覆盖的单位是「方格 x 扇区」）。

    候选点阵与「候选 x (规划方格, 扇区)」的关联矩阵在构造时算一次，
    之后每次规划只是一次矩阵乘法（几毫秒），可以承受滚动时域里的反复调用。
    """

    def __init__(self, 判据栅格, 规划栅格, 间距=220.0, 外扩=700.0):
        self.判据 = 判据栅格
        self.规划 = 规划栅格
        点 = []
        行距 = 间距 * np.sqrt(3) / 2
        j, y = 0, -(C.R_AREA + 外扩)
        while y <= C.R_AREA + 外扩:
            x = -(C.R_AREA + 外扩) + (间距 / 2 if j % 2 else 0.0)
            while x <= C.R_AREA + 外扩:
                if np.hypot(x, y) <= C.R_AREA + 外扩:
                    点.append((x, y))
                x += 间距
            y += 行距
            j += 1
        # 预置构造排在候选表最前，贪心遇到并列时天然优先取它们
        self.构造数 = len(围堵锚点构造)
        self.候选 = np.asarray(list(围堵锚点构造) + 点, dtype=float)
        self.关联 = np.stack([规划栅格.扇区标记(p).ravel().astype(np.float32)
                              for p in self.候选])

    # ------------------------------------------------------------ 查询
    def 残余数(self, 规划掩码):
        return int(规划掩码.sum())

    def 新增覆盖(self, 规划掩码, p):
        return int((规划掩码 & self.规划.扇区标记(p)).sum())

    def 插入代价(self, 路线):
        """把每个候选点插进给定开放路线的最小边际长度。路线首元素是当前位置。"""
        V = np.asarray(路线, dtype=float).reshape(-1, 2)
        P = self.候选
        最小 = np.hypot(P[:, 0] - V[-1, 0], P[:, 1] - V[-1, 1])      # 接在末尾
        for i in range(len(V) - 1):
            a, b = V[i], V[i + 1]
            ab = float(np.hypot(*(b - a)))
            d = (np.hypot(P[:, 0] - a[0], P[:, 1] - a[1]) +
                 np.hypot(P[:, 0] - b[0], P[:, 1] - b[1]) - ab)
            最小 = np.minimum(最小, d)
        return 最小

    def 收尾锚点(self, 判据掩码, 预扣点=(), 上限=8):
        """**只在判据栅格上**为最后残下的那几格挑锚点。

        规划用的是 120 m 的粗采样点阵（为了快），判据用的是 40 m 的完整栅格。
        当残余只剩一两格、且恰好落在粗栅格的判定盲区里时，贪心会认为
        「没什么要覆盖的了」而返回空表——于是任务表为空、主循环在没有判空依据的
        情况下退出。问题三的三次正式测试里有两次栽在这个形状的坑上（P3 §8.4）。
        """
        剩 = 判据掩码.copy()
        for p in 预扣点:
            剩 &= ~self.判据.扇区标记(p)
        出 = []
        while 剩.any() and len(出) < 上限:
            行 = np.where(剩.any(axis=1))[0]
            最好, 最好i = 0, -1
            for i, p in enumerate(self.候选):
                g = int((剩[行] & self.判据.扇区标记(p, 行索引=行)).sum())
                if g > 最好:
                    最好, 最好i = g, i
            if 最好i < 0:
                break                       # 候选点阵够密，正常到不了这里
            出.append(tuple(self.候选[最好i]))
            剩 &= ~self.判据.扇区标记(self.候选[最好i])
        return 出

    def 贪心锚点(self, 规划掩码, 判据掩码, 上限=45, 预扣点=(), 当前位置=None,
                 准则="覆盖", 每米尺度=400.0, 路线=None, 用构造=True):
        """贪心最大覆盖。预扣点是「反正要去的停靠点」，先记它们的覆盖再选锚点。

        准则 = "覆盖每米" 时评分改成「新增覆盖 / 把这个点插进现有路线要多走多少米」，
        这是问题三 §5.6 的结论，在问题四里更值钱——锚点数从 7 涨到二十几个之后，
        锚点巡回本身就成了最大的一项开销。
        """
        剩 = 规划掩码.ravel().astype(np.float32)
        for p in 预扣点:
            剩 = 剩 * (~self.规划.扇区标记(p).ravel())
        出 = []
        代价 = (self.插入代价(路线) if (准则 == "覆盖每米" and 路线 is not None)
                else None)
        # —— 阶段一：优先从**预置围堵构造**里取，只取还有贡献的 ——
        # 一局开始时残余是固定的，最优锚点集与算例无关；现场贪心比离线优化差四成，
        # 差距全落在行进时间上。已被清除停靠顺带覆盖掉的那些构造点会因贡献为 0 被跳过。
        if 用构造:
            while 剩.sum() > 0 and len(出) < 上限:
                计数 = self.关联[:self.构造数] @ 剩
                i = int(np.argmax(计数))
                if 计数[i] <= 0:
                    break
                出.append(tuple(self.候选[i]))
                剩 = 剩 * (1.0 - self.关联[i])
        # —— 阶段二：构造集盖不住的残余（清除停靠改变了覆盖格局时会出现）用点阵补 ——
        while 剩.sum() > 0 and len(出) < 上限:
            计数 = self.关联 @ 剩
            if 代价 is not None:
                得分 = 计数 / (每米尺度 + 代价)
                i = int(np.argmax(得分))
                if 计数[i] <= 0:
                    合格 = np.where(计数 > 0)[0]
                    if not len(合格):
                        break
                    i = int(合格[int(np.argmax(得分[合格]))])
            else:
                i = int(np.argmax(计数))
                if 计数[i] <= 0:
                    break
            出.append(tuple(self.候选[i]))
            剩 = 剩 * (1.0 - self.关联[i])
        # 去冗余：倒序尝试删除，仍能覆盖就删
        改 = True
        while 改 and len(出) > 1:
            改 = False
            for k in range(len(出) - 1, -1, -1):
                试 = 出[:k] + 出[k + 1:]
                剩 = 规划掩码.copy()
                for p in list(预扣点) + 试:
                    剩 &= ~self.规划.扇区标记(p)
                if not 剩.any():
                    出, 改 = 试, True
                    break
        # 收尾兜底：规划栅格上已经没东西可覆盖，但判据栅格上还剩几格
        剩判 = 判据掩码.copy()
        for p in list(预扣点) + list(出):
            剩判 &= ~self.判据.扇区标记(p)
        if 剩判.any():
            出 = list(出) + self.收尾锚点(判据掩码, tuple(预扣点) + tuple(出))
        return 出


_规划器缓存 = {}


def 取规划器(判据栅格, 规划栅格, 间距, 外扩):
    键 = (判据栅格.步长, 判据栅格.扇区数, 规划栅格.步长, 规划栅格.扇区数,
          规划栅格.裕度, 间距, 外扩)
    if 键 not in _规划器缓存:
        _规划器缓存[键] = 锚点规划器(判据栅格, 规划栅格, 间距, 外扩)
    return _规划器缓存[键]


# ================================================================ 方向可行集
_方向中心 = (np.arange(方向分格) + 0.5) * (360.0 / 方向分格)


def 方向可行集(信念, x, 参数, 分格=方向分格):
    """候选源位置为 x 时，定向方向 u 的集员估计（长度 分格 的布尔数组）。

    这是问题四把「距离」与「方向」两种失配统一起来的地方。约束来自两侧：

        收到信号的点 s：  (s - x)·u >= 0     （事实 D0）
        未收到且**保证在接收距离内**的点 q： (q - x)·u < 0

    第二条的前提「保证在接收距离内」由 R_eff 的已知下界给出：
    R_eff >= 1000，且每个曾收到信号的点 s 都给出 R_eff >= |s - x|（公共.保证距离界）。
    只有满足这个前提，才能断定「收不到」是角度原因而不是距离原因。

    引理 D3（镜像必达）在这里是自动成立的：若 s 收到、q 未收到且在距离内，
    则可行的 u 全部满足 u·(s-x) >= 0 > u·(q-x)，于是对 r = 2s - q 必有 u·(r-x) > 0。
    所以本函数算出的「r 被覆盖的把握」自然等于 1，**不需要给镜像点开特例**。
    """
    中心 = _方向中心 if 分格 == 方向分格 else (np.arange(分格) + 0.5) * (360.0 / 分格)
    可行 = np.ones(分格, dtype=bool)
    S = np.asarray([s for s, _ in 信念.信号点], dtype=float).reshape(-1, 2)
    if len(S):
        a = np.degrees(np.arctan2(S[:, 1] - x[1], S[:, 0] - x[0]))
        可行 &= np.all(np.abs(C.角差(中心[None, :], a[:, None])) <= C.半角_定向, axis=0)
    界 = 信念.保证距离界(x)
    N = np.asarray(信念.无信号点, dtype=float).reshape(-1, 2)
    全向可能 = True
    if len(N):
        d = np.hypot(N[:, 0] - x[0], N[:, 1] - x[1])
        N = N[d <= 界]                      # 距离上没保证的点不能用来约束方向
        if len(N):
            # **这一行是问题四的关键推论**：某个无信号点在保证接收距离之内，
            # 说明「源在 x 且是全向源」这个假设已经被否掉——全向源在距离内必然收得到。
            # 于是对这个候选位置而言，剩下的只能是定向源，全向先验必须清零。
            # 不做这一步，策略会一直用 0.5 的先验高估收信把握，
            # 在同一片背面反复空测（实测一局里出现过连续 40 次）。
            全向可能 = bool(_关闭后验)
            b = np.degrees(np.arctan2(N[:, 1] - x[1], N[:, 0] - x[0]))
            可行 &= np.all(np.abs(C.角差(中心[None, :], b[:, None])) > C.半角_定向,
                           axis=0)
    return 可行, 全向可能


class 收信评估器:
    """在一个频道的当前信念下，评估「到 q 去测一次能收到的把握」。

    问题四把这件事拆成「距离」与「方向」两层：

        距离层（与问题三相同，P2 §3.5 的透镜域论证推广到任意观测历史）
            |q - x| <= max(1000, max_s |s - x|)  ==>  距离上必定够得着。
        方向层（问题四新增）
            已证全向    方向必定没问题，取 1
            已证定向    取「可行的 u 里有多大比例覆盖 q」
            未判定      取 全向先验 + (1 - 全向先验) x 上面那个比例

    **做成一个类而不是一个函数，是因为方向可行集只依赖候选源位置 x，与 q 无关。**
    一次补测点选择要评 40 多个候选 q，如果每个 q 都重算一遍可行集，
    开销是这里的四十倍——实测这一处就把单局算力从几分钟压到几秒。

    距离那一层是**下界**（不依赖 R_eff 的分布）；方向那一层依赖「u 在可行弧上均匀」
    这一假设——题面没给定向方向的分布，均匀是最大熵选择，写进假设表。
    """

    def __init__(self, 信念, m, 参数):
        self.信念 = 信念
        P = np.asarray(m["多边形"], dtype=float)
        采样 = [P.mean(axis=0)] + [p for p in P]
        if len(P) >= 2:
            采样 += [(P[i] + P[(i + 1) % len(P)]) / 2 for i in range(len(P))]
        if len(采样) > 13:                   # 顶点很多时抽稀，精度够用、开销可控
            步 = int(np.ceil(len(采样) / 13))
            采样 = 采样[::步]
        self.采样 = [np.asarray(x, dtype=float) for x in 采样]
        self.距界 = [信念.保证距离界(x) for x in self.采样]
        先验 = float(参数.get("全向先验", 0.5))
        if 信念.定向性 == "全向":
            先验 = 1.0
        elif 信念.定向性 == "定向":
            先验 = 0.0
        self.先验 = 先验
        if 先验 >= 1.0:
            self.可行 = [None] * len(self.采样)
            self.样本先验 = [1.0] * len(self.采样)
        else:
            自 = [方向可行集(信念, x, 参数) for x in self.采样]
            self.可行 = [a for a, _ in 自]
            # 逐样本的「全向先验」：该位置上全向假设还没被否掉才保留先验，否则清零
            self.样本先验 = [先验 if 全向可能 else 0.0 for _, 全向可能 in 自]

    def 把握(self, q):
        if not self.采样:
            return 0.0
        总 = 0.0
        for x, 界, 可行, 先验 in zip(self.采样, self.距界, self.可行, self.样本先验):
            if C.距(q, x) > 界:
                continue                    # 距离上没把握，这个样本记 0
            if 可行 is None:
                总 += 1.0
                continue
            n可 = int(可行.sum())
            if n可 == 0:
                总 += 1.0                   # 方向可行集为空说明该位置本就不可行，不扣分
                continue
            角 = np.degrees(np.arctan2(q[1] - x[1], q[0] - x[0]))
            比 = int((可行 & (np.abs(C.角差(_方向中心, 角)) <= C.半角_定向)).sum()) / n可
            总 += 先验 + (1.0 - 先验) * 比
        return 总 / len(self.采样)


def 收信把握(信念, m, q, 参数):
    """单点版，供「就地补测」这类只问一个 q 的场合使用。"""
    return 收信评估器(信念, m, 参数).把握(q)


# ================================================================ 信念状态
class 状态:
    """策略侧维护的全部信息。**不含任何真值**。"""

    def __init__(self, 参数):
        self.参数 = 参数
        self.栅格 = 取栅格(参数["栅格步长"], 参数["扇区数"])
        # 规划栅格：粗一档的采样点阵，只用来给贪心打分。它的裕度取判据栅格的裕度，
        # 正确性不靠它——贪心末尾会在**判据栅格**上核一遍残余，不空就补「收尾锚点」。
        # 若把裕度按规划栅格自己的步长算，有效半径会白白缩掉一成，锚点数多出四分之一。
        self.规划栅格 = 取栅格(参数["规划步长"], 参数["规划扇区数"],
                               裕度=参数["规划裕度"])
        self.规划器 = 取规划器(self.栅格, self.规划栅格,
                               参数["锚点间距"], 参数["锚点外扩"])
        self.信念 = {c: C.频道信念(c, 参数["delta"]) for c in range(1, C.频道数 + 1)}
        # 每个频道**各有一张**判空掩码。问题三 §6.2 的教训：共用一张会在异常重置时
        # 把「有源但被重置」的频道误判成空频道，漏掉一个源。问题四同理。
        self.掩码 = {c: self.栅格.新掩码() for c in range(1, C.频道数 + 1)}
        self.规划掩码 = {c: self.规划栅格.新掩码() for c in range(1, C.频道数 + 1)}
        self.已清除 = set()
        self.已测 = set()                 # (x, y, 频道) 去重：同点同频道重测零信息
        self.已扫点 = set()
        self.盲清计数 = {c: 0 for c in range(1, C.频道数 + 1)}
        self.异常 = []
        self.计数 = {"扫描停靠": 0, "扫描检测": 0, "补测检测": 0, "就地补测": 0,
                     "专程补测": 0, "锚点停靠": 0, "清除停靠": 0,
                     "补测收到": 0, "补测落空": 0, "镜像补测": 0,
                     "判定全向": 0, "判定定向": 0}
        self._指标缓存 = {}
        self._锚点缓存 = None
        self._掩码版本 = 0
        self._联合缓存 = None
        self._标记缓存 = {}

    # ---------------------------------------------------------- 标记缓存
    def _标记(self, 栅格, p):
        """同一个停靠点对整池频道的扇区标记完全相同，算一次就够。"""
        键 = (id(栅格), round(float(p[0]), 3), round(float(p[1]), 3))
        if 键 not in self._标记缓存:
            if len(self._标记缓存) > 64:
                self._标记缓存.clear()
            self._标记缓存[键] = 栅格.扇区标记(p)
        return self._标记缓存[键]

    # ---------------------------------------------------------- 查询
    @property
    def 未探测(self):
        """还没收到过信号、也没被清除的频道。它们要靠「围堵判空」才能收尾。"""
        return {c for c in range(1, C.频道数 + 1)
                if c not in self.已清除 and not self.信念[c].收到信号}

    def 判空集(self):
        return {c for c in self.未探测 if not self.掩码[c].any()}

    def 残余联合(self):
        """还需要覆盖的 (方格, 扇区)：各未探测频道残余掩码的并（判据栅格）。"""
        if self._联合缓存 is not None and self._联合缓存[0] == self._掩码版本:
            return self._联合缓存[1]
        待 = [self.掩码[c] for c in self.未探测]
        m = (np.zeros_like(self.栅格.新掩码()) if not 待
             else np.logical_or.reduce(待))
        待2 = [self.规划掩码[c] for c in self.未探测]
        m2 = (np.zeros_like(self.规划栅格.新掩码()) if not 待2
              else np.logical_or.reduce(待2))
        self._联合缓存 = (self._掩码版本, m, m2)
        return m

    def 残余联合_规划(self):
        self.残余联合()
        return self._联合缓存[2]

    def 全部解决(self):
        for c in range(1, C.频道数 + 1):
            if c in self.已清除:
                continue
            if self.信念[c].收到信号:
                return False
            if self.掩码[c].any():
                return False
        return True

    def 指标(self, c):
        b = self.信念[c]
        键 = (c, b.检测次数, len(b.失败清除点), b.定向性, id(b))
        if self._指标缓存.get("键" + str(c)) != 键:
            self._指标缓存["键" + str(c)] = 键
            self._指标缓存[c] = b.指标()
        return self._指标缓存[c]

    def 已探测未清除(self):
        return [c for c in range(1, C.频道数 + 1)
                if c not in self.已清除 and self.信念[c].收到信号]

    def 锚点(self, 预扣点=(), 当前位置=None, 路线=None):
        准则 = self.参数.get("锚点准则", "覆盖")
        键 = (self._掩码版本, tuple(sorted(预扣点)), 准则,
              None if 当前位置 is None else (round(当前位置[0], -1),
                                             round(当前位置[1], -1)))
        if self._锚点缓存 is None or self._锚点缓存[0] != 键:
            self._锚点缓存 = (键, self.规划器.贪心锚点(
                self.残余联合_规划(), self.残余联合(), 预扣点=预扣点,
                当前位置=当前位置, 准则=准则,
                每米尺度=self.参数.get("锚点每米尺度", 400.0), 路线=路线,
                用构造=self.参数.get("用预置构造", True)))
        return self._锚点缓存[1]

    # ---------------------------------------------------------- 更新
    def _键(self, p, c):
        return (round(float(p[0]), 3), round(float(p[1]), 3), int(c))

    def _并入无信号(self, c, p):
        """把一次 no_signal 并进频道 c 的两张判空掩码。

        判空模式 = "围堵"：问题四的正确判据（命题 D5），只排除被见证的方向扇区。
        判空模式 = "圆盘"：问题三的判据，一次排除整个 1000 m 圆盘内的**全部**方向。
                           **它在问题四里是错的**，只作对照用（基线_问题三判空）。
        """
        if self.参数.get("判空模式", "围堵") == "圆盘":
            for 栅, 掩 in ((self.栅格, self.掩码), (self.规划栅格, self.规划掩码)):
                d = np.hypot(栅.点[:, 0] - p[0], 栅.点[:, 1] - p[1])
                掩[c] = 掩[c] & (d > 栅.有效半径)[:, None]
        else:
            self.掩码[c] = self.掩码[c] & ~self._标记(self.栅格, p)
            self.规划掩码[c] = self.规划掩码[c] & ~self._标记(self.规划栅格, p)
        self._掩码版本 += 1

    def 记录检测(self, p, c, 回):
        self.已测.add(self._键(p, c))
        r = 回["measure_result"]
        旧定向性 = self.信念[c].定向性
        self.信念[c].记录检测(p, r, 回.get("svd_deg"))
        if r == "no_signal":
            self._并入无信号(c, p)
        # **no_signal 之后也要更新定向性**：正是「在保证接收距离内却没收到」这件事
        # 才能否掉全向假设。早先只在收到信号时更新，分类器几乎不触发。
        self.信念[c].更新定向性()
        if self.信念[c].定向性 != 旧定向性:
            self.计数["判定" + self.信念[c].定向性] += 1

    def 记录扫描停靠(self, p):
        self.计数["扫描停靠"] += 1
        self.已扫点.add((round(float(p[0]), 1), round(float(p[1]), 1)))

    def 重建掩码(self, c):
        """按该频道**自己的**无信号点重建判空掩码（重置信念时用）。"""
        self.掩码[c] = self.栅格.新掩码()
        self.规划掩码[c] = self.规划栅格.新掩码()
        for p in self.信念[c].无信号点:
            self._并入无信号(c, p)
        self._掩码版本 += 1

    def 记录清除(self, p, c, 回):
        if 回["clear_result"] == "success":
            self.信念[c].记录清除成功()
            self.已清除.add(c)
        else:
            self.信念[c].记录清除失败(p)
            self.盲清计数[c] += 1


# ================================================================ 几何：预演与补测点
def 预演(信念, q, delta):
    """假设在 q 处收到该频道信号、且示向度恰好指向当前区域形心，问区域会缩成什么样。

    与问题三同源：直接把楔形裁到当前多边形上，不另造近似公式。
    返回 (新直径, 新Rmin)；无法预演时返回 (inf, inf)。
    """
    m = 信念.指标()
    if m is None or m.get("空"):
        return np.inf, np.inf
    P = m["多边形"]
    形心 = np.asarray(P, dtype=float).mean(axis=0)
    if C.距(q, 形心) < 1e-6:
        return m["直径"], m["Rmin"]
    θ = C.方位角(q, 形心)
    新 = list(P)
    for a, b, c in C.几何.楔形半平面(q, θ, delta):
        新 = C.几何.裁剪(新, a, b, c)
        if not 新:
            return np.inf, np.inf
    新 = C.几何.去冗余(新)
    if len(新) < 2:
        return 0.0, 0.0
    d, _ = C.P2模型.求直径快(新)
    _, R = C.P2模型.最小覆盖圆快(新)
    return float(d), float(R)


def 补测点候选(信念, m, 当前位置, 参数):
    """给出若干候选补测点。

    前两类沿用问题三（正横侧移 + 贴着长轴走），第三类是问题四新增的**镜像点**：

        引理 D3：在 s 收到、在 q 未收到（且 q 在接收距离内） ==> r = 2s - q 必定收到。

    它把「换个角度再测」的最坏代价钉死在 2 次检测：第一次大胆取一个大侧移角
    （几何好但可能绕到背面），万一落空，第二次走镜像点必定收到。
    """
    P = np.asarray(m["多边形"], dtype=float)
    D = m["直径"]
    圆心 = np.asarray(m["圆心"], dtype=float)
    _, (A, B) = C.P2模型.求直径快([tuple(p) for p in P])
    A, B = np.asarray(A, dtype=float), np.asarray(B, dtype=float)
    轴 = B - A
    L = float(np.hypot(*轴))
    if L < 1e-9:
        return [tuple(圆心 + np.array([参数["补测最小偏移"], 0.0]))]
    轴 = 轴 / L
    n = np.array([-轴[1], 轴[0]])
    if float(n @ (np.asarray(当前位置, dtype=float) - 圆心)) < 0:
        n = -n
    Λ = D / 2.0
    出 = []
    for λ in 参数["补测λ"]:
        基 = A + λ * (B - A) if D > 120.0 else 圆心
        for κ in 参数["补测κ"]:
            偏 = max(κ * Λ, 参数["补测最小偏移"])
            for s in (1.0, -1.0):
                q = 基 + s * 偏 * n
                出.append((float(q[0]), float(q[1])))
    for λ in (0.15, 0.35, 0.55, 0.75):
        基 = A + λ * (B - A)
        for 偏 in (max(0.12 * Λ, 参数["补测最小偏移"]), 60.0, 150.0):
            q = 基 + 偏 * n
            出.append((float(q[0]), float(q[1])))
    # —— 以成功检测点为锚的正横侧移**对**（问题四的主力候选）——
    # 关键在「以 p 为锚」而不是「以区域长轴为锚」：
    # 引理 D3 的结论 r = p + λ(p-q) 是**锚在 p 上**的，
    # 只有当 q = p + t·n 时，它的镜像才恰好是 q' = p - t·n——
    # 同一个 t、同一条法线，两点到源的距离也相等（都是 sqrt(d²+t²)），
    # 于是「一个在接收距离内」蕴含「另一个也在」，引理的前提自动满足。
    # 早先的候选点绕区域长轴生成，与 p 无关，落空之后拿不到保证点，
    # 定位会在同一片背面反复空测（实测一局对同一频道测了 2424 次，见 分析记录 §6.5）。
    for s0, θ0 in 信念.信号点[-2:]:
        if θ0 is None:
            continue
        s0 = np.asarray(s0, dtype=float)
        轴0 = C.单位向量(θ0)                       # p 指向源的方位
        n0 = np.array([-轴0[1], 轴0[0]])
        d0 = max(C.距(s0, 圆心), 50.0)             # 到区域中心的距离，作为量级
        for 比 in (0.20, 0.40, 0.70, 1.00):
            t = max(比 * d0, 参数["补测最小偏移"])
            for 号 in (1.0, -1.0):
                q = s0 + 号 * t * n0
                出.append((float(q[0]), float(q[1])))
    # —— 一般形式的镜像必达点（引理 D3）——
    if 参数.get("镜像候选", True) and 信念.无信号点 and 信念.信号点:
        近无信号 = sorted(信念.无信号点, key=lambda q: C.距(q, 圆心))[:3]
        for s, _ in 信念.信号点[-2:]:
            s = np.asarray(s, dtype=float)
            for q in 近无信号:
                q = np.asarray(q, dtype=float)
                for λ in (1.0, 0.5):
                    r = s + λ * (s - q)
                    出.append((float(r[0]), float(r[1])))
    return 出


def 选补测点(信念, m, 当前位置, 参数, 已测=()):
    """在候选里挑一个：既要一次把区域压进清除半径，又不能为此多绕路，还得收得到。

    评分 = (走到补测点 + 从补测点走到区域中心) / 速度 + 检测耗时
           + 压不下去的罚 + (1 - 收信把握) x 空测罚

    与问题三的唯一差别在最后一项：「收信把握」现在同时含距离与方向两层（见 收信把握）。
    """
    最好 = (np.inf, None, None, 0.0)
    评 = 收信评估器(信念, m, 参数) if 参数["用收信把握"] else None
    禁 = set(已测)
    # —— 硬规则：上一次补测落空之后，只在「保证收得到」的点里挑 ——
    # 依据是引理 D3（镜像必达）：在 p 收到、在 q 未收到（且 q 在保证接收距离内）
    # ==> 射线 {p + λ(p-q) : λ > 0} 上每一点都在覆盖角内。
    # 这条规则把「换个角度再测」的最坏代价钉死在 **2 次检测**：
    # 第一次可以大胆取一个大侧移角（几何好、但可能绕到背面），
    # 万一落空，第二次走保证点必定收到。
    # 不设这条硬规则、只靠评分里的软罚，实测会出现「连续两百次落空」的退化局面
    # （空测罚取 15 s 那一档，清除率掉到 0.967，见 分析记录 §6.4）——
    # **完备性不能挂在参数的取值上。**
    只要保证 = (参数.get("镜像候选", True) and 信念.最近无信号 is not None
                and 评 is not None and 信念.信号点)
    保证族 = []
    if 只要保证:
        # 引理 D3 给的是**一整条射线** r = s + λ(s - q)（λ > 0 任意），不是一个点。
        # λ 越大方位变化越大（几何越好），但走得越远。
        # 早先直接取 λ = 1 并无条件返回，结果机器狗被甩到几百公里外——
        # 单局路程 233 km、虚拟时间 49000 s（见 分析记录 §6.6）。
        # 正确做法：把整条射线上的若干个点都当候选，**照常按评分挑**，
        # 这样「保证收得到」和「不要绕远路」两件事同时被考虑。
        q0 = np.asarray(信念.最近无信号, dtype=float)
        for s0, _ in list(信念.信号点)[-2:]:
            s0 = np.asarray(s0, dtype=float)
            for λ in (0.25, 0.5, 1.0, 1.75):
                r = s0 + λ * (s0 - q0)
                if np.hypot(*r) > C.R_AREA + 1200.0:      # 跑得太远的直接丢掉
                    continue
                保证族.append((float(r[0]), float(r[1])))
    候选表 = 保证族 if 保证族 else 补测点候选(信念, m, 当前位置, 参数)
    for q in 候选表:
        # **同点同频道重测是零信息**，而且在问题四里格外危险：一次 no_signal 不改变
        # 位置可行集，若不显式去重，规划器会算出同一个点、一遍遍地撞同一堵墙。
        if (round(float(q[0]), 3), round(float(q[1]), 3)) in 禁:
            continue
        p收 = 评.把握(q) if 评 is not None else 1.0
        if p收 <= 0.0:
            continue

        d, R = 预演(信念, q, 参数["delta"])
        行程 = C.距(当前位置, q) + C.距(q, m["圆心"])
        罚 = 0.0 if R <= C.R_CLEAR else (
            30.0 if R <= 参数["盲清阈值"] else 60.0 + min(R, 400.0))
        罚 += (1.0 - p收) * 参数["空测罚"]
        分 = 行程 / C.V_MOVE + C.T_MEASURE + 罚
        if 分 < 最好[0]:
            最好 = (分, q, R, p收)
    if 最好[1] is None and 保证族:
        # 保证点全被测过了，退回普通候选，至少不要卡死
        return 选补测点(信念, m, 当前位置, dict(参数, 镜像候选=False), 已测)
    if 最好[1] is None:                          # 全都可能收不到：退回贴近区域中心
        方向 = np.asarray(m["圆心"], dtype=float) - np.asarray(当前位置, dtype=float)
        n = float(np.hypot(*方向))
        q = (np.asarray(当前位置, dtype=float) + 方向 * min(1.0, 800.0 / max(n, 1e-9))
             ) if n > 1e-9 else np.asarray(m["圆心"], dtype=float)
        return (float(q[0]), float(q[1])), np.inf, 0.0
    return 最好[1], 最好[2], 最好[3]


# ================================================================ 推荐策略
def 推荐策略(狗, 参数=None, 采集轨迹=False):
    """一体化滚动时域策略（问题四版）。返回统计字典。"""
    参数 = dict(默认参数, **(参数 or {}))
    st = 状态(参数)
    轨迹 = []
    狗.进入()
    动作 = 0
    while 动作 < 参数["最多动作"]:
        if st.全部解决():
            break
        if 狗.现实剩余 < 参数["现实时间留白"]:
            st.异常.append("现实时间不足，提前收尾")
            break
        位置 = (float(狗.位置[0]), float(狗.位置[1]))

        # ---------- A. 就地整池扫描（未探测频道，零移动成本） ----------
        if 值得扫描(st, 位置, 参数):
            扫描(狗, st, 位置)
            动作 += 1
            if 采集轨迹:
                轨迹.append(("扫描", *位置, 狗.虚拟时刻))
            continue

        # ---------- B. 就地补测（已探测未定位频道，零移动成本） ----------
        做了 = False
        for c in st.已探测未清除():
            m = st.指标(c)
            if m is None or m.get("空"):
                continue
            if m["Rmin"] <= 参数["盲清阈值"]:
                continue
            if st._键(位置, c) in st.已测:
                continue
            p收 = (收信把握(st.信念[c], m, 位置, 参数)
                   if 参数["用收信把握"] else 1.0)
            if p收 <= 0.0:
                continue
            d, R = 预演(st.信念[c], 位置, 参数["delta"])
            if p收 * (1.0 - d / max(m["直径"], 1e-9)) >= 1.0 - 参数["精测增益γ"]:
                回 = 狗.检测(位置, c)
                st.记录检测(位置, c, 回)
                st.计数["补测检测"] += 1
                st.计数["就地补测"] += 1
                st.信念[c].补测次数 += 1
                st.计数["补测收到" if 回["measure_result"] != "no_signal"
                        else "补测落空"] += 1
                动作 += 1
                做了 = True
                break
        if 做了:
            continue

        # ---------- C. 就地清除 ----------
        目标 = 就地清除目标(st, 位置, 参数)
        if 目标 is not None:
            c, 点 = 目标
            回 = 狗.清除(点, c)
            st.记录清除(点, c, 回)
            动作 += 1
            if 采集轨迹:
                轨迹.append(("清除", *点, 狗.虚拟时刻))
            continue

        # ---------- D. 规划下一站并执行第一段 ----------
        任务 = 构造任务(st, 位置, 参数)
        if not 任务:
            if not st.全部解决():
                st.异常.append("任务表为空但仍有频道未决，被迫退出")
            break
        点表 = [t["点"] for t in 任务]
        顺序, _ = C.开放TSP(位置, 点表)
        第一 = 任务[顺序[0]]
        if 第一["类型"] == "清除":
            st.计数["清除停靠"] += 1
            回 = 狗.清除(第一["点"], 第一["频道"])
            st.记录清除(第一["点"], 第一["频道"], 回)
            if 采集轨迹:
                轨迹.append(("清除", *第一["点"], 狗.虚拟时刻))
        elif 第一["类型"] == "锚点":
            st.计数["锚点停靠"] += 1
            扫描(狗, st, 第一["点"])
            if 采集轨迹:
                轨迹.append(("锚点", *第一["点"], 狗.虚拟时刻))
        else:
            回 = 狗.检测(第一["点"], 第一["频道"])
            st.记录检测(第一["点"], 第一["频道"], 回)
            st.计数["补测检测"] += 1
            st.计数["专程补测"] += 1
            st.信念[第一["频道"]].补测次数 += 1
            st.计数["补测收到" if 回["measure_result"] != "no_signal"
                    else "补测落空"] += 1
            if 第一.get("镜像"):
                st.计数["镜像补测"] += 1
            if 采集轨迹:
                轨迹.append(("补测", *第一["点"], 狗.虚拟时刻))
        动作 += 1
    狗.退出()
    return 收尾统计(狗, st, 轨迹 if 采集轨迹 else None)


def 值得扫描(st, p, 参数):
    """在 p 处把未探测池整池测一遍值不值。

    与问题三同形：代价是 |池| x 6 s，收益折成「覆盖了本该由一个锚点覆盖的那一份残余」。
    唯一的差别是「残余」的单位——问题三数方格，问题四数 (方格, 扇区) 二元组。
    """
    if not st.未探测:
        return False
    if (round(p[0], 1), round(p[1], 1)) in st.已扫点:
        return False
    联合 = st.残余联合_规划()
    残 = st.规划器.残余数(联合)
    if 残 == 0:
        return False
    新增 = st.规划器.新增覆盖(联合, p)
    if 新增 <= 0:
        return False
    还需 = len(st.锚点())
    if 还需 <= 1:
        return True
    return 新增 >= 参数["扫描增益ζ"] * 残 / 还需


def 扫描(狗, st, p):
    """在 p 处把当前未探测池整池测一遍。

    「整池一起测」是刻意的：只有这样，池内各频道的无信号历史才完全相同，
    判空的论证才干净（每个池内频道的方向扇区排除集合是同一个）。
    """
    池 = sorted(st.未探测)
    for c in C.排序检测频道(池, 狗.频道):
        if st._键(p, c) in st.已测:
            continue
        回 = 狗.检测(p, c)
        st.记录检测(p, c, 回)
        st.计数["扫描检测"] += 1
    st.记录扫描停靠(p)


def 就地清除目标(st, 位置, 参数):
    """脚下就能打的目标：已定位且清除点离当前位置不超过半米。"""
    for c in st.已探测未清除():
        m = st.指标(c)
        if m is None or m.get("空"):
            continue
        if m["Rmin"] <= C.R_CLEAR and C.距(位置, m["圆心"]) <= 0.5:
            return c, m["圆心"]
    return None


def 扫清点阵(m, 参数):
    """在可行集上铺一层 20 m 清除盘，逐点开枪必能命中（兜底用）。

    六角排布，间距取 sqrt(3)·R_clear，保证圆盘之并盖住最小覆盖圆。
    点数 ~ (R_min / R_clear)²，区域压到几十米时只要几个点。
    """
    圆心 = np.asarray(m["圆心"], dtype=float)
    R = float(m["Rmin"])
    if R <= C.R_CLEAR:
        return [tuple(圆心)]
    步 = np.sqrt(3.0) * C.R_CLEAR
    行距 = 步 * np.sqrt(3) / 2
    出, j, y = [], 0, -R - 步
    while y <= R + 步:
        x = -R - 步 + (步 / 2 if j % 2 else 0.0)
        while x <= R + 步:
            if np.hypot(x, y) <= R + C.R_CLEAR:
                出.append((float(圆心[0] + x), float(圆心[1] + y)))
            x += 步
        y += 行距
        j += 1
    return 出[:int(参数.get("扫清上限", 60))]


def 构造任务(st, 位置, 参数):
    """把当前所有「必须去的地方」列出来，交给 TSP 排序。

    三类任务：
        清除  已定位（R_min <= 清除半径），或虽略大于清除半径但值得赌一把（盲清）
        补测  已探测但区域还太大，需要换个角度再测一次
        锚点  未探测频道的判空残余，需要专门跑一趟的围堵点

    锚点在最后算，并且**先扣掉前两类停靠点自带的覆盖**——反正都要去那儿，
    顺手扫一遍就够的话就不必再多跑锚点。这一步是「信息与执行合并」的落点，
    在问题四里比问题三更值钱：锚点从 7 个涨到二十几个，能省一个是一个。
    """
    任务 = []
    for c in st.已探测未清除():
        m = st.指标(c)
        if m is None or m.get("空"):
            st.异常.append(f"频道{c}可行集为空")
            重置信念(st, c)
            continue
        if m["Rmin"] <= C.R_CLEAR or (
                m["Rmin"] <= 参数["盲清阈值"] and
                st.盲清计数[c] < 参数["盲清上限"]):
            任务.append({"类型": "清除", "点": m["圆心"], "频道": c})
        elif st.信念[c].补测次数 >= 参数.get("补测预算", 40):
            # 补测预算用尽：改走扫清。**这一步保证了完备性不依赖收敛速度。**
            已打 = {(round(f[0], 1), round(f[1], 1)) for f in st.信念[c].失败清除点}
            候 = [q for q in 扫清点阵(m, 参数)
                  if (round(q[0], 1), round(q[1], 1)) not in 已打]
            if 候:
                if st.信念[c].补测次数 == 参数.get("补测预算", 40):
                    st.异常.append(f"频道{c}补测预算用尽，改走扫清（{len(候)} 个点）")
                顺, _ = C.开放TSP(位置, 候)
                任务.append({"类型": "清除", "点": 候[顺[0]], "频道": c})
            else:
                任务.append({"类型": "清除", "点": m["圆心"], "频道": c})
        else:
            已测点 = {(x, y) for (x, y, cc) in st.已测 if cc == c}
            q, _, p收 = 选补测点(st.信念[c], m, 位置, 参数, 已测=已测点)
            if q is not None:
                任务.append({"类型": "补测", "点": q, "频道": c,
                             "镜像": p收 >= 0.999})
    if st.残余联合().any():
        预扣 = tuple(t["点"] for t in 任务) if 参数["预扣覆盖"] else ()
        路线 = [位置]
        if 任务:
            顺, _ = C.开放TSP(位置, [t["点"] for t in 任务])
            路线 += [任务[i]["点"] for i in 顺]
        for a in st.锚点(预扣点=预扣, 当前位置=位置, 路线=路线):
            任务.append({"类型": "锚点", "点": a, "频道": None})
    return 任务


def 重置信念(st, c):
    """可行集变空说明模型与读数矛盾（理论上不该发生，但实测程序必须能兜住）。

    处理：丢掉楔形约束，只保留不依赖示向度的硬信息，把频道退回未探测池重走围堵流程。
    宁可多花时间，也不能因为一次异常读数就漏掉一个源。
    """
    旧 = st.信念[c]
    新 = C.频道信念(c, st.参数["delta"])
    新.无信号点 = list(旧.无信号点)
    新.失败清除点 = list(旧.失败清除点)
    新.异常 = 旧.异常
    st.信念[c] = 新
    st.重建掩码(c)                       # 退回未探测状态，但用**它自己的**无信号历史
    st._指标缓存.pop(c, None)
    st._指标缓存.pop("键" + str(c), None)
    return False


def 收尾统计(狗, st, 轨迹):
    return {
        "虚拟总时间": 狗.虚拟时刻,
        "检测次数": 狗.检测次数,
        "清除次数": 狗.清除次数,
        "清除成功": 狗.清除成功,
        "判空频道数": len(st.判空集()),
        "未决频道数": sum(1 for c in range(1, C.频道数 + 1)
                          if c not in st.已清除 and
                          (st.信念[c].收到信号 or st.掩码[c].any())),
        "计数": dict(st.计数),
        "异常": list(st.异常),
        "状态": st,
        "轨迹": 轨迹,
    }


# ================================================================ 基线一：先扫后清
def 基线_先扫后清(狗, 参数=None, 锚点表=None):
    """先把判空锚点走一遍（每站测遍所有存活频道），再对已定位的源做 TSP 清除。

    信息与执行完全分离——最容易讲清楚，也最慢：锚点巡回与清除巡回是两条独立的路。
    问题四里锚点多了三倍，这个缺点被放得更大。
    """
    参数 = dict(默认参数, **(参数 or {}))
    st = 状态(参数)
    狗.进入()
    if 锚点表 is None:
        锚点表 = st.锚点()
        顺序, _ = C.开放TSP((0.0, 0.0), 锚点表)
        锚点表 = [锚点表[i] for i in 顺序]
    for p in [(0.0, 0.0)] + list(锚点表):
        池 = sorted(set(range(1, C.频道数 + 1)) - st.已清除)
        for c in C.排序检测频道(池, 狗.频道):
            if st._键(p, c) in st.已测:
                continue
            回 = 狗.检测(p, c)
            st.记录检测(p, c, 回)
        st.记录扫描停靠(p)
    while True:
        待 = [c for c in st.已探测未清除() if not (st.指标(c) or {}).get("空", True)]
        if not 待:
            break
        点表 = [st.指标(c)["圆心"] for c in 待]
        顺序, _ = C.开放TSP(tuple(狗.位置), 点表)
        c = 待[顺序[0]]
        护 = 0
        while 护 < 10:
            m = st.指标(c)
            if m is None or m.get("空"):
                break
            if m["Rmin"] <= C.R_CLEAR or st.盲清计数[c] >= 参数["盲清上限"]:
                回 = 狗.清除(m["圆心"], c)
                st.记录清除(m["圆心"], c, 回)
                if 回["clear_result"] == "success":
                    break
            else:
                q, _, _ = 选补测点(st.信念[c], m, tuple(狗.位置), 参数,
                                  已测={(x, y) for (x, y, cc) in st.已测 if cc == c})
                if q is None or st._键(q, c) in st.已测:
                    回 = 狗.清除(m["圆心"], c)
                    st.记录清除(m["圆心"], c, 回)
                    if 回["clear_result"] == "success":
                        break
                else:
                    回 = 狗.检测(q, c)
                    st.记录检测(q, c, 回)
            护 += 1
        if 护 >= 10:
            st.异常.append(f"频道{c}收尾未收敛")
            st.已清除.add(c)
    护 = 0
    while st.残余联合().any() and 护 < 30:
        锚 = st.锚点()
        if not 锚:
            break
        顺序, _ = C.开放TSP(tuple(狗.位置), 锚)
        扫描(狗, st, 锚[顺序[0]])
        护 += 1
    狗.退出()
    return 收尾统计(狗, st, None)


# ================================================================ 基线二：逐源处理
def 基线_逐源(狗, 参数=None):
    """原点测遍 20 个频道，然后一次只盯一个源，走完再换下一个，最后补判空。"""
    参数 = dict(默认参数, **(参数 or {}))
    st = 状态(参数)
    狗.进入()
    扫描(狗, st, (0.0, 0.0))
    护总 = 0
    while 护总 < 90:
        护总 += 1
        待 = [c for c in st.已探测未清除() if not (st.指标(c) or {}).get("空", True)]
        if 待:
            点表 = [st.指标(c)["圆心"] for c in 待]
            顺序, _ = C.开放TSP(tuple(狗.位置), 点表)
            c = 待[顺序[0]]
            护 = 0
            while 护 < 10:
                m = st.指标(c)
                if m is None or m.get("空"):
                    break
                if m["Rmin"] <= C.R_CLEAR or st.盲清计数[c] >= 参数["盲清上限"]:
                    回 = 狗.清除(m["圆心"], c)
                    st.记录清除(m["圆心"], c, 回)
                    if 回["clear_result"] == "success":
                        break
                else:
                    q, _, _ = 选补测点(st.信念[c], m, tuple(狗.位置), 参数,
                                  已测={(x, y) for (x, y, cc) in st.已测 if cc == c})
                    if q is None or st._键(q, c) in st.已测:
                        回 = 狗.清除(m["圆心"], c)
                        st.记录清除(m["圆心"], c, 回)
                        if 回["clear_result"] == "success":
                            break
                    else:
                        回 = 狗.检测(q, c)
                        st.记录检测(q, c, 回)
                护 += 1
            if 护 >= 10:
                st.异常.append(f"频道{c}收尾未收敛")
                st.已清除.add(c)
            continue
        if st.残余联合().any():
            锚 = st.锚点()
            if not 锚:
                break
            顺序, _ = C.开放TSP(tuple(狗.位置), 锚)
            扫描(狗, st, 锚[顺序[0]])
            continue
        break
    狗.退出()
    return 收尾统计(狗, st, None)


# ================================================================ 基线三：盲清搜索
def 盲清搜索代价(R=C.R_AREA, r=C.R_CLEAR):
    """完全不用示向度，只靠 20 m 清除盘铺满目标圆域的代价（解析估计）。

    这条基线在问题四里的地位比问题三更特殊：它是**唯一完全不受定向影响**的方案，
    因为清除与覆盖角无关（附件 2 §8.2）。代价也因此完全一样——两个量级的差距
    正说明「示向度信息值多少」。
    """
    单点面积 = 1.5 * np.sqrt(3.0) * r * r
    点数 = int(np.ceil(np.pi * R * R / 单点面积))
    列距 = np.sqrt(3.0) * r
    路程 = 点数 * 列距
    return {"清除点数": 点数, "路程": 路程,
            "行进时间": 路程 / C.V_MOVE,
            "清除时间": 点数 * C.T_CLEAR_FAIL,
            "总时间": 路程 / C.V_MOVE + 点数 * C.T_CLEAR_FAIL}


# ================================================================ 理论下界
def 理论下界(案例, 空频道判空次数=None, 参数=None):
    """两条参照线。**它们的性质不同，论文里不能混为一谈。**

    ① 严格下界（真正的下界，任何策略都不可能低于它）

           行进 >= MST({原点} ∪ 源位置) / v      （边长按「走到 20 m 内即可」削短）
         + 清除 >= 5 s x 源数                   （每个源至少要成功清除一次）
         + 检测 >= 5 s x K4 x 空频道数          （每个空频道至少 K4 次检测）

       其中 K4 是问题四判空所需的最少锚点数。这里取**与构造无关的严格下界**
       ceil(3 R²/r²) = 10（判空几何.py ①），不用数值搜索得到的那个上界，
       以保证整条下界是严格的。

    ② 全知参照（**不是下界**）：假设一开始就知道全部真值，走一条 2-opt 巡回依次清除，
       并顺路补上判空所需的围堵锚点。这是一条**可行方案**的代价，是「全知最优」的上界。
       所以实测值除以它得到的倍数可能小于 1，这不矛盾。
    """
    参数 = dict(默认参数, **(参数 or {}))
    if 空频道判空次数 is None:
        空频道判空次数 = int(np.ceil(3.0 * C.R_AREA ** 2 / C.R_RECV_MIN ** 2))
    位置 = 案例.位置表()
    空 = C.频道数 - 案例.源数
    清除 = 案例.源数 * C.T_CLEAR_OK

    MST = C.最小生成树长度(位置, 收缩=2 * C.R_CLEAR, 起点收缩=C.R_CLEAR)
    严格判空检测 = 空频道判空次数 * 空 * C.T_MEASURE        # 不算切频，保证是下界
    严格下界 = MST / C.V_MOVE + 清除 + 严格判空检测

    _, L1 = C.开放TSP((0.0, 0.0), 位置)
    st = 状态(参数)
    补锚 = st.规划器.贪心锚点(st.残余联合_规划(), st.残余联合(), 预扣点=tuple(位置))
    _, L2 = C.开放TSP((0.0, 0.0), list(位置) + list(补锚))
    判空检测 = (空频道判空次数 + len(补锚)) / 2 * 空 * (C.T_MEASURE + C.T_SWITCH) \
        if False else 空 * (len(补锚) + 空频道判空次数) / 2 * (C.T_MEASURE + C.T_SWITCH)
    参照 = L2 / C.V_MOVE + 清除 + 判空检测
    return {"MST路程": MST, "严格行进时间": MST / C.V_MOVE,
            "严格判空检测": 严格判空检测, "严格判空次数": 空频道判空次数,
            "严格下界": 严格下界, "严格下界平均": 严格下界 / 案例.源数,
            "TSP路程": L1, "行进时间": L1 / C.V_MOVE,
            "清除时间": 清除, "判空检测时间": 判空检测,
            "补锚点数": len(补锚), "含判空TSP路程": L2,
            "全知参照": 参照, "全知参照平均": 参照 / 案例.源数}
