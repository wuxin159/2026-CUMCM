N = 60000


def 单位(角):
    return np.stack([np.cos(np.radians(角)), np.sin(np.radians(角))], axis=-1)


# ================================================================ 引理 D0
def 引理D0(rng, n=N):
    """覆盖角 = 半平面：angle(p - G, u) <= 90°  <==>  (p - G)·u >= 0。

    这是问题四全部结论的地基。题面说「有效覆盖角度范围为定向方向两侧各 90°（含）」，
    两侧各 90° 合起来恰好 180°，所以覆盖区域是一个**过 G 的闭半平面**——
    不是一般的扇形。整篇分析（收信锥、镜像必达、围堵判空）都靠这一条的凸性。
    """
    G = rng.uniform(-1800, 1800, (n, 2))
    φ = rng.uniform(0, 360, n)
    p = G + rng.uniform(-1500, 1500, (n, 2))
    d = p - G
    u = 单位(φ)
    夹角 = np.abs(C.角差(np.degrees(np.arctan2(d[:, 1], d[:, 0])), φ))
    点积 = np.einsum("ij,ij->i", d, u)
    # 边界上浮点会互相打架，留一个极小的中性带
    坏 = ((夹角 <= 90 - 1e-6) & (点积 < 0)) | ((夹角 >= 90 + 1e-6) & (点积 > 0))
    return int(坏.sum()), n


# ================================================================ 引理 D1
def 引理D1(rng, n=N // 4):
    """收信锥：若 p1..pk 都在覆盖角内，则 G + cone{p_i - G} 内的每一点都在覆盖角内。

    依据是半平面的凸性（含 G）。这条引理是「补测点怎么选才不会绕到背面」的全部依据。
    """
    坏 = 0
    for _ in range(n):
        G = rng.uniform(-1500, 1500, 2)
        φ = rng.uniform(0, 360)
        u = 单位(φ)
        k = int(rng.integers(1, 4))
        P_ = []
        while len(P_) < k:                     # 只取真的在覆盖角内的点
            q = G + rng.uniform(-1500, 1500, 2)
            if float((q - G) @ u) >= 0:
                P_.append(q)
        λ = rng.uniform(0, 3, k)
        r = G + sum(l * (q - G) for l, q in zip(λ, P_))
        if float((r - G) @ u) < -1e-9:
            坏 += 1
    return 坏, n


# ================================================================ 引理 D2
def 引理D2(rng, n=N // 4):
    """三点包围 ⇒ 全向：G 落在信号点凸包内部时，不存在覆盖全部信号点的 u。

    这是本文唯一能**证明**某频道是全向源的判据（分类器的一半）。
    """
    坏 = 0
    for _ in range(n):
        P_ = rng.uniform(-1500, 1500, (3, 2))
        w = rng.dirichlet(np.ones(3) * 2.0)     # 严格内部的凸组合
        if np.min(w) < 1e-3:
            continue
        G = w @ P_
        角 = np.degrees(np.arctan2(P_[:, 1] - G[1], P_[:, 0] - G[0]))
        # 若存在 u 覆盖全部三点，则三点方位角的最小包含弧不超过 180°
        if C.张角跨度(角) <= 180.0 - 1e-6:
            坏 += 1
    return 坏, n


# ================================================================ 引理 D3
def 引理D3(rng, n=N // 2):
    """镜像必达：在 p 收到、在 q 未收到（且 q 在接收距离内）==>
    对任意 λ > 0，r = p + λ(p - q) 必在覆盖角内。

    证明：(r-G)·u = (1+λ)(p-G)·u - λ(q-G)·u >= 0 + λ·(正数) > 0。∎
    **结论里不含 G**——不需要知道源在哪就能用，这正是它在实战里好用的原因。
    """
    坏 = 0
    for _ in range(n):
        G = rng.uniform(-1500, 1500, 2)
        u = 单位(rng.uniform(0, 360))
        for _ in range(50):
            p = G + rng.uniform(-1200, 1200, 2)
            q = G + rng.uniform(-1200, 1200, 2)
            if float((p - G) @ u) >= 0 > float((q - G) @ u):
                break
        else:
            continue
        λ = float(rng.uniform(0.05, 4.0))
        r = p + λ * (p - q)
        if float((r - G) @ u) <= 0:
            坏 += 1
    return 坏, n


# ================================================================ 引理 D4
def 引理D4(rng, n=N // 4):
    """Farkas 排除：q 落在 cone{p_i - G} 内且在接收距离内时，
    「在 p_i 收到、在 q 未收到」这组观测不可能同时成立。

    等价说法：q - G ∈ cone{p_i - G}  ==>  不存在 u 使 u·(p_i-G) >= 0 (∀i) 且 u·(q-G) < 0。
    这是问题四里 no_signal 唯一还能提供的**位置**信息。
    本文的信念模型没有用它（实测贡献接近噪声，见 分析记录 §7.4），
    但它是模型完整性的一部分，必须验。
    """
    坏 = 0
    for _ in range(n):
        G = rng.uniform(-1200, 1200, 2)
        k = int(rng.integers(2, 4))
        P_ = [G + rng.uniform(-1000, 1000, 2) for _ in range(k)]
        λ = rng.uniform(0, 2, k)
        if λ.sum() < 1e-6:
            continue
        q = G + sum(l * (p - G) for l, p in zip(λ, P_))
        # 若存在 u 同时满足，则说明 Farkas 的方向反了。
        # 用 0.5° 一格的密集方向扫描代替求解器，避免引入额外依赖；一次算完不进 Python 循环。
        U = 单位(np.arange(0, 360, 0.5))
        V = np.asarray([pp - G for pp in P_], dtype=float)
        可 = np.all(V @ U.T >= 0.0, axis=0) & ((q - G) @ U.T < 0.0)
        if bool(可.any()):
            坏 += 1
    return 坏, n


# ================================================================ 命题 D5
def 命题D5(rng, n=N // 20):
    """判空判据：x 被排除  <==>  x ∈ conv{p ∈ N : |p - x| <= 1000}。

    两个方向都要验：
      正向  x 在凸包内 ==> 任何 (u, R_eff) 都与某条 no_signal 矛盾（即确实排除）
      反向  x 不在凸包内 ==> 存在 u 使全部 no_signal 都自洽（即确实不能排除）
    反向这一半同样要紧：它保证判据不是「充分但过强」，否则会白花锚点。
    """
    坏正, 坏反 = 0, 0
    for _ in range(n):
        x = rng.uniform(-1800, 1800, 2)
        k = int(rng.integers(2, 7))
        N_ = rng.uniform(-1600, 1600, (k, 2))
        近 = N_[np.hypot(N_[:, 0] - x[0], N_[:, 1] - x[1]) <= C.R_RECV_MIN]
        if len(近) == 0:
            continue
        角 = np.degrees(np.arctan2(近[:, 1] - x[1], 近[:, 0] - x[0]))
        在凸包内 = C.张角跨度(角) >= 180.0       # 方向正张成 R² <=> x ∈ conv
        # 密集扫描 u：找一个与全部近点都不矛盾的方向（即全部近点都在覆盖角外）
        u角 = np.arange(0, 360, 0.25)
        自洽 = np.all(np.abs(C.角差(角[:, None], u角[None, :])) > 90.0, axis=0)
        有自洽 = bool(自洽.any())
        if 在凸包内 and 有自洽:
            坏正 += 1
        if (not 在凸包内) and (not 有自洽):
            坏反 += 1
    return 坏正 + 坏反, n


# ================================================================ 引理 E1（楔形含真值）
def 引理E1(rng, n=N):
    """楔形含真值：报数 = round(真值 + ε, 2)，|ε| <= 1°，故 |报数 - 真值| <= 1.005° = δ。

    与问题三、P1 §5.4 相同。问题四里示向度的语义没有变化
    （附录 1 第 4 条：覆盖角内场强只随距离衰减，与角度无关），所以这条照搬。
    """
    真 = rng.uniform(0, 360, n)
    ε = rng.uniform(-C.DELTA, C.DELTA, n)
    报 = np.round((真 + ε) % 360.0, 2)
    偏 = np.abs(C.角差(报, 真))
    return int((偏 > C.DELTA_算法 + 1e-12).sum()), n, float(偏.max())


# ================================================================ 引理 E2（扇区标记的保守性）
def 引理E2(rng, 栅格, n=N // 4):
    """扇区标记的保守性：被标记的 (方格, 扇区) 里，方格内任何一点 y 与扇区内任何方向 u
    都满足「源在 y、朝向 u 时应当在 p 收到信号」，即 |p-y| <= 1000 且 (p-y)·u >= 0。

    这是「掩码全空 ==> 该频道无源」的全部依据。
    离散化必须两侧都保守：距离留 步长/sqrt2 的裕度，角度留 arcsin(ε/d) 的裕度。
    """
    坏距, 坏角 = 0, 0
    h = 栅格.步长
    for _ in range(n):
        i = int(rng.integers(0, 栅格.n))
        x = 栅格.点[i]
        p = x + rng.uniform(-1200, 1200, 2)
        标 = 栅格.扇区标记(p, 行索引=np.array([i]))[0]
        j = int(rng.integers(0, 栅格.扇区数))
        if not 标[j]:
            continue
        # 方格内任取一点 y、扇区内任取一个方向 u
        y = x + rng.uniform(-h / 2, h / 2, 2)
        角 = 栅格.边界[j] + rng.uniform(0, 栅格.扇宽)
        u = 单位(角)
        if float(np.hypot(*(p - y))) > C.R_RECV_MIN + 1e-9:
            坏距 += 1
        if float((p - y) @ u) < -1e-9:
            坏角 += 1
    return 坏距 + 坏角, n, 坏距, 坏角


def 引理E2_对照(rng, 栅格, n=N // 4):
    """判别性对照：把角度裕度置零（直接用 90° 而不是 90° - arcsin(ε/d)），应当报警。"""
    坏 = 0
    h = 栅格.步长
    for _ in range(n):
        i = int(rng.integers(0, 栅格.n))
        x = 栅格.点[i]
        p = x + rng.uniform(-900, 900, 2)
        d = float(np.hypot(*(p - x)))
        if d < 1e-6 or d > 栅格.有效半径:
            continue
        θ = C.方位角(x, p)
        j = int(rng.integers(0, 栅格.扇区数))
        边 = [栅格.边界[j], 栅格.边界[j + 1]]
        if max(abs(float(C.角差(e, θ))) for e in 边) > 90.0:     # 无裕度的判定
            continue
        y = x + rng.uniform(-h / 2, h / 2, 2)
        角 = 栅格.边界[j] + rng.uniform(0, 栅格.扇宽)
        if float((p - y) @ 单位(角)) < -1e-9:
            坏 += 1
    return 坏, n


# ================================================================ 引理 E3（栅格覆盖目标圆域）
def 引理E3(栅格):
    """判据栅格的方格覆盖整个目标圆域：圆域内每一点都落在某个方格里。

    方格中心取到 R + 步长/sqrt2，所以圆域内任一点到最近格心的距离不超过 步长/sqrt2。
    """
    轴 = np.linspace(-C.R_AREA, C.R_AREA, 160)
    Xg, Yg = np.meshgrid(轴, 轴)
    内 = np.hypot(Xg, Yg) <= C.R_AREA
    点 = np.stack([Xg[内], Yg[内]], axis=1)
    最近 = np.empty(len(点))
    for i in range(0, len(点), 512):            # 分块，避免一次开出上 GB 的距离矩阵
        块 = 点[i:i + 512]
        最近[i:i + 512] = np.min(
            np.abs(块[:, None, :] - 栅格.点[None, :, :]).max(axis=2), axis=1)
    return int((最近 > 栅格.步长 / 2 + 1e-9).sum()), len(点), float(最近.max())


# ================================================================ 引理 E4
def 引理E4(rng, 判据, 规划, 规划器, n=300):
    """规划器**永远不会在判据栅格还有残余时交白卷**。

    这一条替换掉了一个看上去更自然、但**实际上不成立**的命题：
    「规划栅格判定覆盖 ⇒ 判据栅格判定覆盖」。
    要让那条蕴含成立，规划栅格的裕度必须取 判据裕度 + 判据步长·sqrt2 = 84.9 m，
    有效排除半径从 971.7 m 缩到 915 m，锚点数因此多出一成半。
    本文没有付这个代价，而是**把正确性从规划器挪到判据**：

        贪心锚点() 的最后一步一定在**判据栅格**上核一遍残余，
        不空就调用 收尾锚点() 继续补，直到判据栅格上再无残余。

    于是要验的不是那条蕴含，而是这条：**返回的锚点集一定能把判据掩码清空**。
    只要它成立，主循环的退出条件（全部解决 读的也是判据掩码）就永远有依据——
    这正是问题三 §8.4 那个「规划器认为没事可做、主循环无依据退出」的坑的根治法。
    实测把裕度按「看上去更自然」的方式设成 28.3 m 时，那条蕴含在 20000 次抽样里
    有 19% 不成立；而本条在同样的随机掩码上一次都没失效。
    """
    坏, 空任务 = 0, 0
    for _ in range(n):
        m判 = 判据.新掩码()
        m规 = 规划.新掩码()
        for _ in range(int(rng.integers(0, 14))):      # 随机若干次 no_signal
            p = rng.uniform(-2200, 2200, 2)
            m判 &= ~判据.扇区标记(p)
            m规 &= ~规划.扇区标记(p)
        if not m判.any():
            continue
        锚 = 规划器.贪心锚点(m规, m判, 上限=60)
        if not 锚:
            空任务 += 1
            坏 += 1
            continue
        余 = m判.copy()
        for a in 锚:
            余 &= ~判据.扇区标记(a)
        if 余.any():
            坏 += 1
    return 坏, n, 空任务


def 引理E4_对照(rng, 判据, 规划, 规划器, n=4000):
    """判别性对照：那条「规划覆盖 ⇒ 判据覆盖」的蕴含在当前裕度下确实不成立。

    列出来不是为了показать失败，而是为了说明**为什么不能把正确性挂在规划器上**。
    """
    坏 = 0
    ρ = 判据.步长 * np.sqrt(2.0)
    比 = int(round(规划.扇宽 / 判据.扇宽))
    for _ in range(n):
        p = rng.uniform(-2500, 2500, 2)
        粗 = 规划.扇区标记(p)
        行 = np.where(粗.any(axis=1))[0]
        if not len(行):
            continue
        i = int(rng.choice(行))
        j = int(rng.choice(np.where(粗[i])[0]))
        x = 规划.点[i]
        d = np.hypot(判据.点[:, 0] - x[0], 判据.点[:, 1] - x[1])
        邻 = np.where(d <= ρ + 1e-9)[0]
        if not len(邻):
            continue
        细 = 判据.扇区标记(p, 行索引=邻)
        起 = int(round(规划.边界[j] / 判据.扇宽))
        if not 细[:, 起:起 + 比].all():
            坏 += 1
    return 坏, n


# ================================================================ 引理 E5（清除与覆盖角无关）
def 引理E5(rng, n=20000):
    """R_min <= 20 m ==> 走到最小覆盖圆心开枪必定成功，**与干扰源是否定向无关**。

    依据：附件 2 §8.2 明文「无论全向还是定向，只要指定频道的干扰源距离 position
    小于等于 20 m，都能够精确定位并清除，不受定向干扰源有效覆盖角度范围的限制」。
    直接后果：**一旦定位成功，清除环节与问题三完全一样**；
    而且「盲清」在问题四里比问题三更值钱——检测可能因为角度而落空，开枪不会。
    """
    import 模拟器 as S
    坏 = 0
    for _ in range(n):
        G = rng.uniform(-1700, 1700, 2)
        φ = None if rng.uniform() < 0.5 else float(rng.uniform(0, 360))
        案 = S.案例([{"频道": 3, "x": float(G[0]), "y": float(G[1]),
                      "R_eff": 1200.0, "定向方向": φ}],
                    S.电磁环境(np.random.default_rng(0), 模式="零"))
        后端 = S.本地后端(案)
        后端.enter()
        # 圆心取在距源不超过 20 m 的任意位置，方向任取
        角 = rng.uniform(0, 360)
        d = rng.uniform(0, C.R_CLEAR)
        c = G + d * 单位(角)
        回 = 后端.clear(float(c[0]), float(c[1]), 3)
        if 回["clear_result"] != "success":
            坏 += 1
    return 坏, n


