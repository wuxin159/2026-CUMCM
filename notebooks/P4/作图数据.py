# ================================================================ 一、判据对照
def 判据对照():
    """问题三 7 个锚点、问题四 24 个锚点，折成每个空频道的判空代价。"""
    行 = []
    for 名, K, L in (("问题三：圆盘覆盖", 7, 6166.2),
                     ("问题四：半圆盘围堵", len(P.围堵锚点构造),
                      C.开放TSP((0.0, 0.0), P.围堵锚点构造)[1])):
        for 空 in range(3, 11):
            行.append({"方案": 名, "锚点数": K, "巡回长度": L, "空频道数": 空,
                       "判空检测秒": K * 空 * (C.T_MEASURE + C.T_SWITCH),
                       "锚点行进秒": L / C.V_MOVE,
                       "合计秒": K * 空 * (C.T_MEASURE + C.T_SWITCH) + L / C.V_MOVE})
    return pd.DataFrame(行)


# ================================================================ 二、围堵示意
def 围堵示意():
    """一个候选位置 x 与它周围的无信号点：哪些方向已被见证、哪些还没有。

    画出来就能一眼看清问题四与问题三的差别：问题三一个见证者就够，
    问题四要把 x 围起来——少一个方向没被见证，x 就排除不掉。
    """
    x = np.array([0.0, 0.0])
    锚 = [(800.0, 0.0), (-600.0, 500.0), (-100.0, -900.0)]
    行 = []
    for k in (1, 2, 3):
        用 = 锚[:k]
        角 = [C.方位角(x, p) for p in 用]
        跨 = C.张角跨度(角)
        for j, p in enumerate(用):
            行.append({"情形": f"{k}个无信号点", "序": j, "px": p[0], "py": p[1],
                       "方位角": C.方位角(x, p), "距离": C.距(x, p),
                       "最大角隙": 360.0 - 跨 if k > 1 else 360.0,
                       "已排除": (跨 >= 180.0) if k >= 3 else False})
    return pd.DataFrame(行)


# ================================================================ 三、锚点布局
def 锚点布局():
    锚 = list(P.围堵锚点构造)
    顺序, L = C.开放TSP((0.0, 0.0), 锚)
    行 = []
    for 次, i in enumerate(顺序):
        行.append({"访问序": 次 + 1, "x": 锚[i][0], "y": 锚[i][1],
                   "距原点": float(np.hypot(*锚[i])),
                   "在区域外": float(np.hypot(*锚[i])) > C.R_AREA,
                   "巡回总长": L})
    return pd.DataFrame(行)


# ================================================================ 四、定向几何示意
def 定向几何():
    """三件事画在一起：半平面覆盖、收信锥、镜像必达。"""
    G = np.array([0.0, 0.0])
    φ = 35.0
    u = C.单位向量(φ)
    行 = []
    行.append({"元素": "源", "x": G[0], "y": G[1], "角": φ, "说明": "定向源与定向方向"})
    # 覆盖半平面的边界线（过 G、法向 u）
    n = np.array([-u[1], u[0]])
    for s in (-1200.0, 1200.0):
        行.append({"元素": "覆盖边界", "x": G[0] + s * n[0], "y": G[1] + s * n[1],
                   "角": np.nan, "说明": "覆盖角的边界（过源、法向为定向方向）"})
    # 两个成功检测点与它们张成的收信锥
    p1 = G + 900.0 * C.单位向量(φ - 60.0)
    p2 = G + 700.0 * C.单位向量(φ + 55.0)
    for 名, p in (("检测点1", p1), ("检测点2", p2)):
        行.append({"元素": 名, "x": p[0], "y": p[1], "角": C.方位角(G, p),
                   "说明": "收到信号"})
    # 一个未收到的点与它的镜像
    q = G + 800.0 * C.单位向量(φ + 150.0)
    r = p1 + (p1 - q)
    行.append({"元素": "落空点", "x": q[0], "y": q[1], "角": C.方位角(G, q),
               "说明": "未收到（在背面）"})
    行.append({"元素": "镜像点", "x": r[0], "y": r[1], "角": C.方位角(G, r),
               "说明": "r = p1 + (p1 - q)，必在覆盖角内"})
    return pd.DataFrame(行)


# ================================================================ 五、单局全景
def 单局(案例, 名="A"):
    后端 = S.本地后端(案例)
    狗 = S.机器狗(后端, 记录日志=True)
    快照 = []
    原 = P.状态.记录检测

    def 挂(self, p, c, 回):
        原(self, p, c, 回)
        for cc in self.已探测未清除():
            m = self.指标(cc)
            if m and not m.get("空"):
                快照.append({"检测序": 狗.检测次数, "频道": cc,
                             "Rmin": m["Rmin"], "直径": m["直径"],
                             "虚拟时刻": 狗.虚拟时刻})
    P.状态.记录检测 = 挂
    try:
        r = P.推荐策略(狗, None, 采集轨迹=True)
    finally:
        P.状态.记录检测 = 原
    st = r["状态"]
    轨 = pd.DataFrame([{"类型": t[0], "x": t[1], "y": t[2], "虚拟时刻": t[3]}
                       for t in (r["轨迹"] or [])])
    日志 = pd.DataFrame(狗.日志)
    路径 = 日志[日志["动作"].isin(["measure", "clear"])][
        ["x", "y", "虚拟时刻", "动作", "频道", "结果"]].reset_index(drop=True)
    # 同一停靠点的连续动作压成一个点，轨迹才画得干净
    路径 = 路径.loc[(路径[["x", "y"]].diff().abs().sum(axis=1) > 1e-6) |
                    (路径.index == 0)].reset_index(drop=True)
    源 = pd.DataFrame([{**s, "定向方向": (np.nan if s["定向方向"] is None
                                          else s["定向方向"]),
                        "是定向": s["定向方向"] is not None,
                        "已清除": int(s["频道"]) in st.已清除} for s in 案例.源表])
    进度 = 日志[(日志["动作"] == "clear") & (日志["结果"] == "success")][
        ["虚拟时刻"]].reset_index(drop=True)
    进度["已清除数"] = np.arange(1, len(进度) + 1)
    return 轨, 路径, 源, pd.DataFrame(快照), 进度, r


# ================================================================ 六、进度曲线（三种策略）
def 进度曲线(案例):
    出 = []
    for 名, f, par in (("推荐策略", P.推荐策略, None),
                       ("基线一：先扫后清", P.基线_先扫后清, None),
                       ("基线二：逐源处理", P.基线_逐源, None)):
        狗 = S.机器狗(S.本地后端(案例), 记录日志=True)
        f(狗, par)
        日 = pd.DataFrame(狗.日志)
        成 = 日[(日["动作"] == "clear") & (日["结果"] == "success")]
        出.append(pd.DataFrame({"策略": 名, "虚拟时刻": [0.0] + list(成["虚拟时刻"]),
                                "已清除数": np.arange(0, len(成) + 1)}))
    return pd.concat(出, ignore_index=True)


# ================================================================ 七、收信把握校准
def 把握校准(案例表):
    """「收信把握」预测值 vs 实际收信率。模型检验里最有说服力的一张图。

    把握是一个概率预测，检验它的正确方式是**校准**：把预测值分档，
    看每一档里实际收到信号的比例是否落在对角线上。
    预测 0.8 的那一档若实际只有 0.2，说明模型系统性高估——
    本目录第一版就栽在这里（见 分析记录 §6.2）。
    """
    记 = []
    原选 = P.选补测点
    待 = {}

    def 选(b, m, pos, par, 已测=(), *a, **kw):
        # 透传其余参数（后续 / 返回分），只截获「预测把握」这一项用于校准
        出 = 原选(b, m, pos, par, 已测, *a, **kw)
        q, R, p = 出[0], 出[1], 出[2]
        if q is not None:
            待[(b.频道, round(q[0], 3), round(q[1], 3))] = p
        return 出
    P.选补测点 = 选
    原检 = S.机器狗.检测

    def 检(self, 位置, 频道):
        回 = 原检(self, 位置, 频道)
        k = (频道, round(位置[0], 3), round(位置[1], 3))
        if k in 待:
            记.append({"预测把握": 待[k],
                       "实际收到": int(回["measure_result"] != "no_signal")})
        return 回
    S.机器狗.检测 = 检
    try:
        for 案 in 案例表:
            P.推荐策略(S.机器狗(S.本地后端(案), 记录日志=False))
    finally:
        P.选补测点 = 原选
        S.机器狗.检测 = 原检
    df = pd.DataFrame(记)
    if df.empty:
        return df
    df["档"] = pd.cut(df["预测把握"], np.linspace(0, 1, 11))
    出 = df.groupby("档", observed=True).agg(
        次数=("实际收到", "size"), 预测均值=("预测把握", "mean"),
        实际比例=("实际收到", "mean")).reset_index()
    出["档"] = [f"{i.left:.1f}~{i.right:.1f}" for i in 出["档"]]
    return 出


